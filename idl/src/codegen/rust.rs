/// Rust code generation backend.
///
/// Generates .rs files with `#[derive(DdsType)]` structs from the resolved IDL model.

use crate::naming;
use crate::types::*;

pub struct RustOptions {
    pub crate_path: String,
}

impl Default for RustOptions {
    fn default() -> Self {
        Self {
            crate_path: "int2dds".to_string(),
        }
    }
}

pub fn generate(model: &IdlModel, idl_filename: &str, opts: &RustOptions) -> String {
    let mut gen = RustGen {
        out: String::new(),
        indent: 0,
        opts,
    };
    gen.emit_file(model, idl_filename);
    gen.out
}

struct RustGen<'a> {
    out: String,
    indent: usize,
    opts: &'a RustOptions,
}

impl<'a> RustGen<'a> {
    fn emit_file(&mut self, model: &IdlModel, idl_filename: &str) {
        self.line(&format!(
            "//! Auto-generated by int2dds-idl from {}",
            idl_filename
        ));
        self.line("//! DO NOT EDIT - changes will be overwritten");
        self.line("");
        self.line(&format!("use {}::prelude::*;", self.opts.crate_path));
        self.line(&format!("use {}_derive::DdsType;", self.opts.crate_path));
        self.line("");

        for e in &model.enums {
            self.emit_enum(e);
            self.line("");
        }

        for s in &model.structs {
            self.emit_struct(s);
            self.line("");
        }
    }

    fn emit_enum(&mut self, e: &ResolvedEnum) {
        let rust_name = naming::to_pascal_case(&e.name);
        self.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, DdsType)]");
        self.line("#[repr(i32)]");
        self.line(&format!("pub enum {} {{", rust_name));
        self.indent += 1;
        for v in &e.variants {
            let variant_name = naming::to_pascal_case(&v.name);
            self.line(&format!("{} = {},", variant_name, v.value));
        }
        self.indent -= 1;
        self.line("}");
    }

    fn emit_struct(&mut self, s: &ResolvedStruct) {
        let rust_name = naming::to_pascal_case(&s.name);

        // Derives
        self.line("#[derive(Debug, Clone, PartialEq, DdsType)]");

        // Type-level attributes
        let mut type_attrs = Vec::new();
        if self.opts.crate_path != "int2dds" {
            type_attrs.push(format!("crate_path = \"{}\"", self.opts.crate_path));
        }
        match s.extensibility {
            ExtensibilityKind::Final => {} // default, no annotation needed
            ExtensibilityKind::Appendable => type_attrs.push("extensibility = \"Appendable\"".to_string()),
            ExtensibilityKind::Mutable => type_attrs.push("extensibility = \"Mutable\"".to_string()),
        }
        if !type_attrs.is_empty() {
            self.line(&format!("#[dds_type({})]", type_attrs.join(", ")));
        }

        self.line(&format!("pub struct {} {{", rust_name));
        self.indent += 1;

        for m in &s.members {
            self.emit_field(m);
        }

        self.indent -= 1;
        self.line("}");
    }

    fn emit_field(&mut self, m: &ResolvedMember) {
        // Build field-level #[dds(...)] attributes
        let mut dds_attrs = Vec::new();
        if m.is_key {
            dds_attrs.push("key".to_string());
        }
        if let Some(id) = m.member_id {
            dds_attrs.push(format!("id = {}", id));
        }
        if m.is_optional {
            dds_attrs.push("optional".to_string());
        }
        if m.must_understand {
            dds_attrs.push("must_understand".to_string());
        }

        // Check for bound on string/sequence
        match &m.resolved_type {
            ResolvedType::String { bound: Some(n) } => {
                dds_attrs.push(format!("bound = {}", n));
            }
            ResolvedType::Sequence { bound: Some(n), .. } => {
                dds_attrs.push(format!("bound = {}", n));
            }
            _ => {}
        }

        if !dds_attrs.is_empty() {
            self.line(&format!("#[dds({})]", dds_attrs.join(", ")));
        }

        let type_str = self.type_to_rust(&m.resolved_type);
        let final_type = if m.is_optional {
            format!("Option<{}>", type_str)
        } else {
            type_str
        };

        self.line(&format!("pub {}: {},", m.name, final_type));
    }

    fn type_to_rust(&self, ty: &ResolvedType) -> String {
        match ty {
            ResolvedType::Bool => "bool".to_string(),
            ResolvedType::U8 => "u8".to_string(),
            ResolvedType::I8 => "i8".to_string(),
            ResolvedType::I16 => "i16".to_string(),
            ResolvedType::U16 => "u16".to_string(),
            ResolvedType::I32 => "i32".to_string(),
            ResolvedType::U32 => "u32".to_string(),
            ResolvedType::I64 => "i64".to_string(),
            ResolvedType::U64 => "u64".to_string(),
            ResolvedType::F32 => "f32".to_string(),
            ResolvedType::F64 => "f64".to_string(),
            ResolvedType::Char => "char".to_string(),
            ResolvedType::String { .. } => "String".to_string(),
            ResolvedType::Sequence { element, .. } => {
                format!("Vec<{}>", self.type_to_rust(element))
            }
            ResolvedType::Array { element, size } => {
                format!("[{}; {}]", self.type_to_rust(element), size)
            }
            ResolvedType::Struct(name) | ResolvedType::Enum(name) => {
                // Use simple name (last component after ::)
                let simple = name.rsplit("::").next().unwrap_or(name);
                naming::to_pascal_case(simple)
            }
        }
    }

    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::parse_idl;
    use crate::resolver::resolve;

    #[test]
    fn test_hello_world_codegen() {
        let defs = parse_idl(
            r#"
            @extensibility(APPENDABLE)
            struct HelloWorld {
                unsigned long index;
                string message;
            };
            "#,
        )
        .unwrap();
        let model = resolve(defs).unwrap();
        let code = generate(&model, "HelloWorld.idl", &RustOptions::default());

        assert!(code.contains("#[derive(Debug, Clone, PartialEq, DdsType)]"));
        assert!(code.contains("#[dds_type(extensibility = \"Appendable\")]"));
        assert!(code.contains("pub struct HelloWorld {"));
        assert!(code.contains("pub index: u32,"));
        assert!(code.contains("pub message: String,"));
    }

    #[test]
    fn test_keyed_struct_codegen() {
        let defs = parse_idl(
            r#"
            struct SensorData {
                @key long sensor_id;
                double temperature;
                string<128> location;
            };
            "#,
        )
        .unwrap();
        let model = resolve(defs).unwrap();
        let code = generate(&model, "SensorData.idl", &RustOptions::default());

        assert!(code.contains("#[dds(key)]"));
        assert!(code.contains("pub sensor_id: i32,"));
        assert!(code.contains("#[dds(bound = 128)]"));
        assert!(code.contains("pub location: String,"));
    }

    #[test]
    fn test_enum_codegen() {
        let defs = parse_idl("enum Color { RED, GREEN = 5, BLUE };").unwrap();
        let model = resolve(defs).unwrap();
        let code = generate(&model, "Color.idl", &RustOptions::default());

        assert!(code.contains("#[repr(i32)]"));
        assert!(code.contains("pub enum Color {"));
        assert!(code.contains("Red = 0,"));
        assert!(code.contains("Green = 5,"));
        assert!(code.contains("Blue = 6,"));
    }
}
