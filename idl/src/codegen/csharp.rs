/// C# code generation backend.
///
/// Generates C# classes with CDR serialization methods
/// that use the Int2Dds C# CDR library.

use crate::naming;
use crate::types::*;

/// Options for C# code generation.
#[derive(Debug, Clone)]
pub struct CSharpOptions {
    /// Namespace for the generated types (default: "GeneratedTypes")
    pub namespace: String,
}

impl Default for CSharpOptions {
    fn default() -> Self {
        Self::new()
    }
}

impl CSharpOptions {
    pub fn new() -> Self {
        Self {
            namespace: "GeneratedTypes".to_string(),
        }
    }
}

/// Generate C# code from the IDL model.
pub fn generate(model: &IdlModel, idl_filename: &str, opts: &CSharpOptions) -> String {
    let mut gen = CsGen {
        out: String::new(),
        opts,
        model,
        indent: 0,
    };
    gen.emit_file(idl_filename);
    gen.out
}

struct CsGen<'a> {
    out: String,
    opts: &'a CSharpOptions,
    model: &'a IdlModel,
    indent: usize,
}

impl<'a> CsGen<'a> {
    fn emit_file(&mut self, idl_filename: &str) {
        // File header
        self.line(&format!(
            "// Auto-generated by int2dds-idl from {}",
            idl_filename
        ));
        self.line("// DO NOT EDIT");
        self.line("");
        self.line("using Int2Dds.Cdr;");
        self.line("using Int2Dds.Types;");
        self.line("");
        self.line(&format!("namespace {};", self.opts.namespace));
        self.line("");

        // Enums first (may be referenced by structs)
        for e in &self.model.enums.clone() {
            self.emit_enum(e);
            self.line("");
        }

        // Bitmasks
        for b in &self.model.bitmasks.clone() {
            self.emit_bitmask(b);
            self.line("");
        }

        // Structs
        for s in &self.model.structs.clone() {
            self.emit_struct(s);
            self.line("");
        }
    }

    // ---- Enum ----

    fn emit_enum(&mut self, e: &ResolvedEnum) {
        let name = naming::to_pascal_case(&e.name);
        self.line(&format!("public enum {}", name));
        self.line("{");
        self.indent += 1;
        for v in &e.variants {
            let variant_name = naming::to_pascal_case(&v.name);
            self.line(&format!("{} = {},", variant_name, v.value));
        }
        self.indent -= 1;
        self.line("}");
    }

    // ---- Bitmask ----

    fn emit_bitmask(&mut self, b: &ResolvedBitmask) {
        let name = naming::to_pascal_case(&b.name);
        self.line("[Flags]");
        self.line(&format!("public enum {} : uint", name));
        self.line("{");
        self.indent += 1;
        for flag in &b.flags {
            let flag_name = naming::to_pascal_case(&flag.name);
            self.line(&format!("{} = 1 << {},", flag_name, flag.position));
        }
        self.indent -= 1;
        self.line("}");
    }

    // ---- Struct ----

    fn emit_struct(&mut self, s: &ResolvedStruct) {
        let class_name = naming::to_pascal_case(&s.name);
        let ext_name = match s.extensibility {
            ExtensibilityKind::Final => "Final",
            ExtensibilityKind::Appendable => "Appendable",
            ExtensibilityKind::Mutable => "Mutable",
        };

        let has_key = s.members.iter().any(|m| m.is_key);

        // Class declaration
        self.line(&format!(
            "public class {} : IDdsType<{}>",
            class_name, class_name
        ));
        self.line("{");
        self.indent += 1;

        // Static metadata
        self.line(&format!(
            "public static string DdsTypeName => \"{}\";",
            s.qualified_name
        ));
        self.line(&format!(
            "public static Extensibility TypeExtensibility => Extensibility.{};",
            ext_name
        ));
        self.line(&format!(
            "public static bool HasKey => {};",
            if has_key { "true" } else { "false" }
        ));
        self.line("");

        // Properties
        for m in &s.members {
            let prop_name = naming::to_pascal_case(&m.name);
            let cs_type = self.type_to_csharp(&m.resolved_type);
            let default = self.default_value(&m.resolved_type);
            if self.needs_initializer(&m.resolved_type) {
                self.line(&format!(
                    "public {} {} {{ get; set; }} = {};",
                    cs_type, prop_name, default
                ));
            } else {
                self.line(&format!(
                    "public {} {} {{ get; set; }}",
                    cs_type, prop_name
                ));
            }
        }
        self.line("");

        // Default constructor
        self.line(&format!("public {}() {{ }}", class_name));
        self.line("");

        // SerializeCdr method
        self.emit_serialize_cdr(s);
        self.line("");

        // DeserializeCdr static method
        self.emit_deserialize_cdr(s);
        self.line("");

        // DeserializeCdrInline internal static method
        self.emit_deserialize_cdr_inline(s);
        self.line("");

        // SerializeKey method
        self.emit_serialize_key(s);

        self.indent -= 1;
        self.line("}");
    }

    fn type_to_csharp(&self, ty: &ResolvedType) -> String {
        match ty {
            ResolvedType::Bool => "bool".to_string(),
            ResolvedType::U8 => "byte".to_string(),
            ResolvedType::I8 => "sbyte".to_string(),
            ResolvedType::I16 => "short".to_string(),
            ResolvedType::U16 => "ushort".to_string(),
            ResolvedType::I32 => "int".to_string(),
            ResolvedType::U32 => "uint".to_string(),
            ResolvedType::I64 => "long".to_string(),
            ResolvedType::U64 => "ulong".to_string(),
            ResolvedType::F32 => "float".to_string(),
            ResolvedType::F64 => "double".to_string(),
            ResolvedType::Char => "char".to_string(),
            ResolvedType::WChar => "char".to_string(),
            ResolvedType::String { .. } => "string".to_string(),
            ResolvedType::WString { .. } => "string".to_string(),
            ResolvedType::Sequence { element, .. } => {
                format!("List<{}>", self.type_to_csharp(element))
            }
            ResolvedType::Array { element, .. } => {
                format!("{}[]", self.type_to_csharp(element))
            }
            ResolvedType::Map { key, value, .. } => {
                format!(
                    "Dictionary<{}, {}>",
                    self.type_to_csharp(key),
                    self.type_to_csharp(value)
                )
            }
            ResolvedType::Struct(name) => naming::to_pascal_case(name),
            ResolvedType::Enum(name) => naming::to_pascal_case(name),
            ResolvedType::Bitmask(name) => naming::to_pascal_case(name),
        }
    }

    fn needs_initializer(&self, ty: &ResolvedType) -> bool {
        matches!(
            ty,
            ResolvedType::String { .. }
                | ResolvedType::WString { .. }
                | ResolvedType::Sequence { .. }
                | ResolvedType::Array { .. }
                | ResolvedType::Map { .. }
                | ResolvedType::Struct(_)
        )
    }

    fn default_value(&self, ty: &ResolvedType) -> String {
        match ty {
            ResolvedType::Bool => "false".to_string(),
            ResolvedType::U8 | ResolvedType::I8 => "0".to_string(),
            ResolvedType::I16 | ResolvedType::U16 => "0".to_string(),
            ResolvedType::I32 | ResolvedType::U32 => "0".to_string(),
            ResolvedType::I64 | ResolvedType::U64 => "0".to_string(),
            ResolvedType::F32 => "0.0f".to_string(),
            ResolvedType::F64 => "0.0".to_string(),
            ResolvedType::Char => "'\\0'".to_string(),
            ResolvedType::WChar => "'\\0'".to_string(),
            ResolvedType::String { .. } => "\"\"".to_string(),
            ResolvedType::WString { .. } => "\"\"".to_string(),
            ResolvedType::Sequence { element, .. } => {
                format!("new List<{}>()", self.type_to_csharp(element))
            }
            ResolvedType::Array { element, size } => {
                format!("new {}[{}]", self.type_to_csharp(element), size)
            }
            ResolvedType::Map { key, value, .. } => {
                format!(
                    "new Dictionary<{}, {}>()",
                    self.type_to_csharp(key),
                    self.type_to_csharp(value)
                )
            }
            ResolvedType::Struct(name) => {
                format!("new {}()", naming::to_pascal_case(name))
            }
            ResolvedType::Enum(name) => {
                // Use 0 cast to enum type
                let cs_name = naming::to_pascal_case(name);
                if let Some(e) = self.model.enums.iter().find(|e| &e.name == name) {
                    if let Some(v) = e.variants.first() {
                        return format!(
                            "{}.{}",
                            cs_name,
                            naming::to_pascal_case(&v.name)
                        );
                    }
                }
                format!("({})0", cs_name)
            }
            ResolvedType::Bitmask(name) => {
                format!("({})0", naming::to_pascal_case(name))
            }
        }
    }

    // ---- Serialization ----

    fn emit_serialize_cdr(&mut self, s: &ResolvedStruct) {
        self.line("public byte[] SerializeCdr()");
        self.line("{");
        self.indent += 1;
        self.line("var w = new CdrWriter(TypeExtensibility);");

        match s.extensibility {
            ExtensibilityKind::Final => {
                for m in &s.members {
                    let accessor = naming::to_pascal_case(&m.name);
                    self.emit_write_field(&m.resolved_type, &accessor);
                }
            }
            ExtensibilityKind::Appendable => {
                self.line("var _dt = w.DheaderBegin();");
                for m in &s.members {
                    let accessor = naming::to_pascal_case(&m.name);
                    self.emit_write_field(&m.resolved_type, &accessor);
                }
                self.line("w.DheaderFinalize(_dt);");
            }
            ExtensibilityKind::Mutable => {
                self.line("var _dt = w.DheaderBegin();");
                for (i, m) in s.members.iter().enumerate() {
                    let member_id = m.member_id.unwrap_or(i as u32);
                    let must_understand = if m.must_understand { "true" } else { "false" };
                    self.line(&format!(
                        "var _et{} = w.EmheaderBegin({}, {});",
                        i, member_id, must_understand
                    ));
                    let accessor = naming::to_pascal_case(&m.name);
                    self.emit_write_field(&m.resolved_type, &accessor);
                    self.line(&format!("w.EmheaderFinalize(_et{});", i));
                }
                self.line("w.WriteSentinel();");
                self.line("w.DheaderFinalize(_dt);");
            }
        }

        self.line("return w.ToBytes();");
        self.indent -= 1;
        self.line("}");
    }

    fn emit_write_field(&mut self, ty: &ResolvedType, accessor: &str) {
        match ty {
            ResolvedType::Bool => self.line(&format!("w.WriteBool({});", accessor)),
            ResolvedType::U8 => self.line(&format!("w.WriteU8({});", accessor)),
            ResolvedType::I8 => self.line(&format!("w.WriteI8({});", accessor)),
            ResolvedType::I16 => self.line(&format!("w.WriteI16({});", accessor)),
            ResolvedType::U16 => self.line(&format!("w.WriteU16({});", accessor)),
            ResolvedType::I32 => self.line(&format!("w.WriteI32({});", accessor)),
            ResolvedType::U32 => self.line(&format!("w.WriteU32({});", accessor)),
            ResolvedType::I64 => self.line(&format!("w.WriteI64({});", accessor)),
            ResolvedType::U64 => self.line(&format!("w.WriteU64({});", accessor)),
            ResolvedType::F32 => self.line(&format!("w.WriteF32({});", accessor)),
            ResolvedType::F64 => self.line(&format!("w.WriteF64({});", accessor)),
            ResolvedType::Char => {
                self.line(&format!("w.WriteU8((byte){});", accessor));
            }
            ResolvedType::WChar => {
                self.line(&format!("w.WriteU16((ushort){});", accessor));
            }
            ResolvedType::String { .. } => {
                self.line(&format!("w.WriteString({});", accessor));
            }
            ResolvedType::WString { .. } => {
                self.line(&format!("w.WriteString({});", accessor));
            }
            ResolvedType::Enum(_) => {
                self.line(&format!("w.WriteEnum((int){});", accessor));
            }
            ResolvedType::Bitmask(_) => {
                self.line(&format!("w.WriteU32((uint){});", accessor));
            }
            ResolvedType::Struct(_) => {
                self.line("{");
                self.indent += 1;
                self.line(&format!(
                    "var _nested = {}.SerializeCdr();",
                    accessor
                ));
                self.line("w.WriteBytes(_nested.AsSpan(4)); // Skip 4-byte encap header");
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Sequence { element, .. } => {
                self.line(&format!("w.WriteSeqHeader((uint){}.Count);", accessor));
                self.line(&format!("foreach (var _item in {})", accessor));
                self.line("{");
                self.indent += 1;
                self.emit_write_field(element, "_item");
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Array { element, .. } => {
                self.line(&format!("foreach (var _item in {})", accessor));
                self.line("{");
                self.indent += 1;
                self.emit_write_field(element, "_item");
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Map { key, value, .. } => {
                self.line(&format!("w.WriteSeqHeader((uint){}.Count);", accessor));
                self.line(&format!("foreach (var _entry in {})", accessor));
                self.line("{");
                self.indent += 1;
                self.emit_write_field(key, "_entry.Key");
                self.emit_write_field(value, "_entry.Value");
                self.indent -= 1;
                self.line("}");
            }
        }
    }

    fn emit_deserialize_cdr(&mut self, s: &ResolvedStruct) {
        let class_name = naming::to_pascal_case(&s.name);

        self.line(&format!(
            "public static {} DeserializeCdr(ReadOnlySpan<byte> data)",
            class_name
        ));
        self.line("{");
        self.indent += 1;
        self.line("var r = new CdrReader(data);");
        self.line(&format!("var obj = new {}();", class_name));

        match s.extensibility {
            ExtensibilityKind::Final => {
                for m in &s.members {
                    let prop_name = naming::to_pascal_case(&m.name);
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                }
            }
            ExtensibilityKind::Appendable => {
                self.line("var (_dSize, _dStart) = r.ReadDheader();");
                for m in &s.members {
                    let prop_name = naming::to_pascal_case(&m.name);
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                }
                self.line("r.ReadDheaderEnd(_dSize, _dStart);");
            }
            ExtensibilityKind::Mutable => {
                self.line("var (_dSize, _dStart) = r.ReadDheader();");
                self.line("while (!r.IsSentinel)");
                self.line("{");
                self.indent += 1;
                self.line("var (_mid, _mlen, _mu) = r.ReadEmheader();");

                let mut first = true;
                for (i, m) in s.members.iter().enumerate() {
                    let member_id = m.member_id.unwrap_or(i as u32);
                    let prop_name = naming::to_pascal_case(&m.name);
                    if first {
                        self.line(&format!("if (_mid == {})", member_id));
                        first = false;
                    } else {
                        self.line(&format!("else if (_mid == {})", member_id));
                    }
                    self.line("{");
                    self.indent += 1;
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                    self.indent -= 1;
                    self.line("}");
                }
                self.line("else");
                self.line("{");
                self.indent += 1;
                self.line("r.Skip((int)_mlen);");
                self.indent -= 1;
                self.line("}");

                self.indent -= 1;
                self.line("}");
                self.line("r.Skip(4); // consume sentinel");
                self.line("r.ReadDheaderEnd(_dSize, _dStart);");
            }
        }

        self.line("return obj;");
        self.indent -= 1;
        self.line("}");
    }

    fn emit_deserialize_cdr_inline(&mut self, s: &ResolvedStruct) {
        let class_name = naming::to_pascal_case(&s.name);

        self.line(&format!(
            "internal static {} DeserializeCdrInline(CdrReader r)",
            class_name
        ));
        self.line("{");
        self.indent += 1;
        self.line(&format!("var obj = new {}();", class_name));

        match s.extensibility {
            ExtensibilityKind::Final => {
                for m in &s.members {
                    let prop_name = naming::to_pascal_case(&m.name);
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                }
            }
            ExtensibilityKind::Appendable => {
                self.line("var (_dSize, _dStart) = r.ReadDheader();");
                for m in &s.members {
                    let prop_name = naming::to_pascal_case(&m.name);
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                }
                self.line("r.ReadDheaderEnd(_dSize, _dStart);");
            }
            ExtensibilityKind::Mutable => {
                self.line("var (_dSize, _dStart) = r.ReadDheader();");
                self.line("while (!r.IsSentinel)");
                self.line("{");
                self.indent += 1;
                self.line("var (_mid, _mlen, _mu) = r.ReadEmheader();");

                let mut first = true;
                for (i, m) in s.members.iter().enumerate() {
                    let member_id = m.member_id.unwrap_or(i as u32);
                    let prop_name = naming::to_pascal_case(&m.name);
                    if first {
                        self.line(&format!("if (_mid == {})", member_id));
                        first = false;
                    } else {
                        self.line(&format!("else if (_mid == {})", member_id));
                    }
                    self.line("{");
                    self.indent += 1;
                    self.emit_read_field(&m.resolved_type, &prop_name, "obj");
                    self.indent -= 1;
                    self.line("}");
                }
                self.line("else");
                self.line("{");
                self.indent += 1;
                self.line("r.Skip((int)_mlen);");
                self.indent -= 1;
                self.line("}");

                self.indent -= 1;
                self.line("}");
                self.line("r.Skip(4); // consume sentinel");
                self.line("r.ReadDheaderEnd(_dSize, _dStart);");
            }
        }

        self.line("return obj;");
        self.indent -= 1;
        self.line("}");
    }

    fn emit_read_field(&mut self, ty: &ResolvedType, name: &str, obj: &str) {
        match ty {
            ResolvedType::Bool => {
                self.line(&format!("{}.{} = r.ReadBool();", obj, name));
            }
            ResolvedType::U8 => {
                self.line(&format!("{}.{} = r.ReadU8();", obj, name));
            }
            ResolvedType::I8 => {
                self.line(&format!("{}.{} = r.ReadI8();", obj, name));
            }
            ResolvedType::I16 => {
                self.line(&format!("{}.{} = r.ReadI16();", obj, name));
            }
            ResolvedType::U16 => {
                self.line(&format!("{}.{} = r.ReadU16();", obj, name));
            }
            ResolvedType::I32 => {
                self.line(&format!("{}.{} = r.ReadI32();", obj, name));
            }
            ResolvedType::U32 => {
                self.line(&format!("{}.{} = r.ReadU32();", obj, name));
            }
            ResolvedType::I64 => {
                self.line(&format!("{}.{} = r.ReadI64();", obj, name));
            }
            ResolvedType::U64 => {
                self.line(&format!("{}.{} = r.ReadU64();", obj, name));
            }
            ResolvedType::F32 => {
                self.line(&format!("{}.{} = r.ReadF32();", obj, name));
            }
            ResolvedType::F64 => {
                self.line(&format!("{}.{} = r.ReadF64();", obj, name));
            }
            ResolvedType::Char => {
                self.line(&format!("{}.{} = (char)r.ReadU8();", obj, name));
            }
            ResolvedType::WChar => {
                self.line(&format!("{}.{} = (char)r.ReadU16();", obj, name));
            }
            ResolvedType::String { .. } => {
                self.line(&format!("{}.{} = r.ReadString();", obj, name));
            }
            ResolvedType::WString { .. } => {
                self.line(&format!("{}.{} = r.ReadString();", obj, name));
            }
            ResolvedType::Enum(enum_name) => {
                let cs_name = naming::to_pascal_case(enum_name);
                self.line(&format!(
                    "{}.{} = ({})r.ReadEnum();",
                    obj, name, cs_name
                ));
            }
            ResolvedType::Bitmask(bitmask_name) => {
                let cs_name = naming::to_pascal_case(bitmask_name);
                self.line(&format!(
                    "{}.{} = ({})r.ReadU32();",
                    obj, name, cs_name
                ));
            }
            ResolvedType::Struct(struct_name) => {
                let cs_name = naming::to_pascal_case(struct_name);
                self.line(&format!(
                    "{}.{} = {}.DeserializeCdrInline(r);",
                    obj, name, cs_name
                ));
            }
            ResolvedType::Sequence { element, .. } => {
                let count_var = format!("_{name}Count");
                let cs_elem = self.type_to_csharp(element);
                self.line(&format!("var {} = r.ReadSeqHeader();", count_var));
                self.line(&format!(
                    "{}.{} = new List<{}>((int){});",
                    obj, name, cs_elem, count_var
                ));
                self.line(&format!("for (var _i = 0; _i < {}; _i++)", count_var));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(element, "_item");
                self.line(&format!("{}.{}.Add(_item);", obj, name));
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Array { element, size } => {
                let cs_elem = self.type_to_csharp(element);
                self.line(&format!(
                    "{}.{} = new {}[{}];",
                    obj, name, cs_elem, size
                ));
                self.line(&format!("for (var _i = 0; _i < {}; _i++)", size));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(element, "_item");
                self.line(&format!("{}.{}[_i] = _item;", obj, name));
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Map { key, value, .. } => {
                let count_var = format!("_{name}Count");
                let cs_key = self.type_to_csharp(key);
                let cs_val = self.type_to_csharp(value);
                self.line(&format!("var {} = r.ReadSeqHeader();", count_var));
                self.line(&format!(
                    "{}.{} = new Dictionary<{}, {}>((int){});",
                    obj, name, cs_key, cs_val, count_var
                ));
                self.line(&format!("for (var _i = 0; _i < {}; _i++)", count_var));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(key, "_k");
                self.emit_read_field_into_var(value, "_v");
                self.line(&format!("{}.{}[_k] = _v;", obj, name));
                self.indent -= 1;
                self.line("}");
            }
        }
    }

    /// Emit a read expression that assigns to a local variable.
    fn emit_read_field_into_var(&mut self, ty: &ResolvedType, var_name: &str) {
        match ty {
            ResolvedType::Bool => {
                self.line(&format!("var {} = r.ReadBool();", var_name));
            }
            ResolvedType::U8 => {
                self.line(&format!("var {} = r.ReadU8();", var_name));
            }
            ResolvedType::I8 => {
                self.line(&format!("var {} = r.ReadI8();", var_name));
            }
            ResolvedType::I16 => {
                self.line(&format!("var {} = r.ReadI16();", var_name));
            }
            ResolvedType::U16 => {
                self.line(&format!("var {} = r.ReadU16();", var_name));
            }
            ResolvedType::I32 => {
                self.line(&format!("var {} = r.ReadI32();", var_name));
            }
            ResolvedType::U32 => {
                self.line(&format!("var {} = r.ReadU32();", var_name));
            }
            ResolvedType::I64 => {
                self.line(&format!("var {} = r.ReadI64();", var_name));
            }
            ResolvedType::U64 => {
                self.line(&format!("var {} = r.ReadU64();", var_name));
            }
            ResolvedType::F32 => {
                self.line(&format!("var {} = r.ReadF32();", var_name));
            }
            ResolvedType::F64 => {
                self.line(&format!("var {} = r.ReadF64();", var_name));
            }
            ResolvedType::Char => {
                self.line(&format!("var {} = (char)r.ReadU8();", var_name));
            }
            ResolvedType::WChar => {
                self.line(&format!("var {} = (char)r.ReadU16();", var_name));
            }
            ResolvedType::String { .. } => {
                self.line(&format!("var {} = r.ReadString();", var_name));
            }
            ResolvedType::WString { .. } => {
                self.line(&format!("var {} = r.ReadString();", var_name));
            }
            ResolvedType::Enum(enum_name) => {
                let cs_name = naming::to_pascal_case(enum_name);
                self.line(&format!(
                    "var {} = ({})r.ReadEnum();",
                    var_name, cs_name
                ));
            }
            ResolvedType::Bitmask(bitmask_name) => {
                let cs_name = naming::to_pascal_case(bitmask_name);
                self.line(&format!(
                    "var {} = ({})r.ReadU32();",
                    var_name, cs_name
                ));
            }
            ResolvedType::Struct(struct_name) => {
                let cs_name = naming::to_pascal_case(struct_name);
                self.line(&format!(
                    "var {} = {}.DeserializeCdrInline(r);",
                    var_name, cs_name
                ));
            }
            ResolvedType::Sequence { element, .. } => {
                let count_var = format!("{var_name}Count");
                let cs_elem = self.type_to_csharp(element);
                self.line(&format!("var {} = r.ReadSeqHeader();", count_var));
                self.line(&format!(
                    "var {} = new List<{}>((int){});",
                    var_name, cs_elem, count_var
                ));
                self.line(&format!("for (var _j = 0; _j < {}; _j++)", count_var));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(element, "_inner");
                self.line(&format!("{}.Add(_inner);", var_name));
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Array { element, size } => {
                let cs_elem = self.type_to_csharp(element);
                self.line(&format!(
                    "var {} = new {}[{}];",
                    var_name, cs_elem, size
                ));
                self.line(&format!("for (var _j = 0; _j < {}; _j++)", size));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(element, "_inner");
                self.line(&format!("{}[_j] = _inner;", var_name));
                self.indent -= 1;
                self.line("}");
            }
            ResolvedType::Map { key, value, .. } => {
                let count_var = format!("{var_name}Count");
                let cs_key = self.type_to_csharp(key);
                let cs_val = self.type_to_csharp(value);
                self.line(&format!("var {} = r.ReadSeqHeader();", count_var));
                self.line(&format!(
                    "var {} = new Dictionary<{}, {}>((int){});",
                    var_name, cs_key, cs_val, count_var
                ));
                self.line(&format!("for (var _j = 0; _j < {}; _j++)", count_var));
                self.line("{");
                self.indent += 1;
                self.emit_read_field_into_var(key, "_mk");
                self.emit_read_field_into_var(value, "_mv");
                self.line(&format!("{}[_mk] = _mv;", var_name));
                self.indent -= 1;
                self.line("}");
            }
        }
    }

    fn emit_serialize_key(&mut self, s: &ResolvedStruct) {
        let key_fields: Vec<&ResolvedMember> = s.members.iter().filter(|m| m.is_key).collect();

        if key_fields.is_empty() {
            self.line("public byte[] SerializeKey() => [];");
        } else {
            self.line("public byte[] SerializeKey()");
            self.line("{");
            self.indent += 1;
            self.line("var w = new CdrKeyWriter();");
            for m in key_fields {
                let accessor = naming::to_pascal_case(&m.name);
                self.emit_write_key_field(&m.resolved_type, &accessor);
            }
            self.line("return w.ToBytes();");
            self.indent -= 1;
            self.line("}");
        }
    }

    fn emit_write_key_field(&mut self, ty: &ResolvedType, accessor: &str) {
        match ty {
            ResolvedType::Bool => self.line(&format!("w.WriteBool({});", accessor)),
            ResolvedType::U8 => self.line(&format!("w.WriteU8({});", accessor)),
            ResolvedType::I8 => self.line(&format!("w.WriteI8({});", accessor)),
            ResolvedType::I16 => self.line(&format!("w.WriteI16({});", accessor)),
            ResolvedType::U16 => self.line(&format!("w.WriteU16({});", accessor)),
            ResolvedType::I32 => self.line(&format!("w.WriteI32({});", accessor)),
            ResolvedType::U32 => self.line(&format!("w.WriteU32({});", accessor)),
            ResolvedType::I64 => self.line(&format!("w.WriteI64({});", accessor)),
            ResolvedType::U64 => self.line(&format!("w.WriteU64({});", accessor)),
            ResolvedType::F32 => self.line(&format!("w.WriteF32({});", accessor)),
            ResolvedType::F64 => self.line(&format!("w.WriteF64({});", accessor)),
            ResolvedType::Char => {
                self.line(&format!("w.WriteU8((byte){});", accessor));
            }
            ResolvedType::WChar => {
                self.line(&format!("w.WriteU16((ushort){});", accessor));
            }
            ResolvedType::String { .. } => {
                self.line(&format!("w.WriteString({});", accessor));
            }
            ResolvedType::WString { .. } => {
                self.line(&format!("w.WriteString({});", accessor));
            }
            ResolvedType::Enum(_) => {
                self.line(&format!("w.WriteEnum((int){});", accessor));
            }
            ResolvedType::Bitmask(_) => {
                self.line(&format!("w.WriteU32((uint){});", accessor));
            }
            ResolvedType::Struct(_)
            | ResolvedType::Sequence { .. }
            | ResolvedType::Array { .. }
            | ResolvedType::Map { .. } => {
                // Complex types in keys are not common
                self.line(&format!("// TODO: Complex key field {}", accessor));
            }
        }
    }

    // ---- Helpers ----

    fn line(&mut self, s: &str) {
        if s.is_empty() {
            self.out.push('\n');
        } else {
            for _ in 0..self.indent {
                self.out.push_str("    ");
            }
            self.out.push_str(s);
            self.out.push('\n');
        }
    }

    #[allow(dead_code)]
    fn raw(&mut self, s: &str) {
        self.out.push_str(s);
    }
}
