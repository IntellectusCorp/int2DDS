/// C header code generation backend.
///
/// Generates .h files with struct definitions and inline CDR serialization functions
/// that use the int2dds_cdr.h utility library.
use crate::codegen::flatten_array;
use crate::naming;
use crate::types::*;

/// `{2, 3}`-style initializer body for a dims array in declaration order.
fn dims_literal(dims: &[u32]) -> String {
    dims.iter().map(|d| d.to_string()).collect::<Vec<_>>().join(", ")
}

/// String representation mode for C code generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum StringMode {
    /// Current behavior: char field[N] fixed arrays.
    /// Default for backwards compatibility.
    #[default]
    FixedArray,
    /// OMG standard: char* pointers with dynamic allocation.
    Pointer,
}

pub struct COptions {
    pub default_string_bound: u32,
    pub string_mode: StringMode,
}

impl Default for COptions {
    fn default() -> Self {
        Self { default_string_bound: 256, string_mode: StringMode::FixedArray }
    }
}

/// Element kinds whose sequence/array bodies can be moved with one call.
/// See `CGen::bulk_element` for what qualifies and why.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BulkElem {
    /// Fixed-width primitive whose C memory bytes are its CDR wire bytes, plus that width.
    Prim(u32),
    /// `boolean` — one octet on the wire, but the copy needs a 0/1 normalization pass.
    Bool,
}

pub fn generate(model: &IdlModel, idl_filename: &str, opts: &COptions) -> String {
    let mut gen = CGen { out: String::new(), opts, model };
    gen.emit_file(idl_filename);
    gen.out
}

/// Render a constant value as a C `#define` body.
fn c_const_value(value: &ConstValue) -> String {
    match value {
        ConstValue::Int(v) => v.to_string(),
        ConstValue::Float(v) => format!("{:?}", v),
        ConstValue::Bool(v) => v.to_string(),
        ConstValue::Str(v) => format!("{:?}", v),
        ConstValue::Ident(v) => v.rsplit("::").next().unwrap_or(v).to_string(),
    }
}

struct CGen<'a> {
    out: String,
    opts: &'a COptions,
    model: &'a IdlModel,
}

impl<'a> CGen<'a> {
    fn emit_file(&mut self, idl_filename: &str) {
        let output_name = naming::idl_to_output_name(idl_filename);
        let guard = naming::to_include_guard(&format!("{}_idl.h", output_name));

        self.raw(&format!("/**\n * Auto-generated by int2dds-idl from {}\n * DO NOT EDIT - changes will be overwritten\n */\n", idl_filename));
        self.raw(&format!("#ifndef {}\n#define {}\n\n", guard, guard));
        self.raw("#include <stdbool.h>\n#include <stdint.h>\n#include <string.h>\n");

        // Include stdlib.h for malloc/free when using pointer strings
        if self.opts.string_mode == StringMode::Pointer {
            self.raw("#include <stdlib.h>\n");
        }

        self.raw("\n#include \"int2dds_cdr.h\"\n\n");

        self.emit_constants();

        // Enums first (may be referenced by structs)
        for e in &self.model.enums {
            self.emit_enum(e);
            self.raw("\n");
        }

        // Bitmasks
        for b in &self.model.bitmasks {
            self.emit_bitmask(b);
            self.raw("\n");
        }

        // Bitsets
        for b in &self.model.bitsets {
            self.emit_bitset(b);
            self.raw("\n");
        }

        // Phase 1: All type definitions (structs and unions may reference each other)
        // Forward-declare all structs and unions
        for s in &self.model.structs {
            self.raw(&format!("typedef struct {} {};\n", s.name, s.name));
        }
        for u in &self.model.unions {
            self.raw(&format!("typedef struct {} {};\n", u.name, u.name));
        }
        self.raw("\n");

        // Struct and union full definitions, interleaved so that structs containing
        // union members by value have the union defined first, and vice-versa.
        {
            let union_names: Vec<&str> =
                self.model.unions.iter().map(|u| u.name.as_str()).collect();
            let mut union_emitted = vec![false; self.model.unions.len()];

            for s in &self.model.structs {
                // Before emitting this struct, emit any unions it references by value
                for m in &s.members {
                    if let ResolvedType::Struct(ref name) = m.resolved_type {
                        if let Some(idx) = union_names.iter().position(|u| *u == name.as_str()) {
                            if !union_emitted[idx] {
                                self.emit_union_typedef(&self.model.unions[idx]);
                                union_emitted[idx] = true;
                            }
                        }
                    }
                }
                self.emit_struct_header(s);
                self.emit_struct_typedef(s);
                self.raw("\n");
            }

            // Emit remaining unions not yet emitted
            for (idx, u) in self.model.unions.iter().enumerate() {
                if !union_emitted[idx] {
                    self.emit_union_typedef(u);
                }
            }
        }

        // Phase 2: All functions in dependency order
        // Use the original definition order from the model, interleaving structs and unions
        {
            let mut struct_idx = 0;
            let mut union_idx = 0;
            // Emit functions following the combined order:
            // unions before the structs that reference them, structs before the unions that reference them.
            // Since the IDL resolver outputs types in dependency order within each category,
            // we interleave: for each struct, emit any pending union functions first if the struct references them.
            for s in &self.model.structs {
                // Emit union functions for unions that this struct may reference
                while union_idx < self.model.unions.len() {
                    // Check if any struct member references this union
                    let u_name = &self.model.unions[union_idx].name;
                    let struct_needs_union = s.members.iter().any(
                        |m| matches!(&m.resolved_type, ResolvedType::Struct(n) if n == u_name),
                    );
                    if struct_needs_union {
                        self.emit_union_functions(&self.model.unions[union_idx]);
                        self.raw("\n");
                        union_idx += 1;
                    } else {
                        break;
                    }
                }
                self.emit_struct_functions(s);
                self.raw("\n");
                struct_idx += 1;
            }
            let _ = struct_idx;
            // Emit remaining union functions
            while union_idx < self.model.unions.len() {
                self.emit_union_functions(&self.model.unions[union_idx]);
                self.raw("\n");
                union_idx += 1;
            }
        }

        self.raw(&format!("#endif /* {} */\n", guard));
    }

    // ---- Enum ----

    fn emit_enum(&mut self, e: &ResolvedEnum) {
        let prefix = naming::to_screaming_snake(&e.name);
        self.raw(&format!("typedef enum {} {{\n", e.name));
        for (i, v) in e.variants.iter().enumerate() {
            let variant_name = format!("{}_{}", prefix, v.name.to_uppercase());
            let comma = if i + 1 < e.variants.len() { "," } else { "" };
            self.raw(&format!("    {} = {}{}\n", variant_name, v.value, comma));
        }
        self.raw(&format!("}} {};\n", e.name));
    }

    // ---- Bitmask ----

    fn emit_bitmask(&mut self, b: &ResolvedBitmask) {
        let c_type = bitmask_c_type(b.bit_bound);
        self.raw(&format!("typedef {} {};\n", c_type, b.name));
        let prefix = naming::to_screaming_snake(&b.name);
        for flag in &b.flags {
            let flag_name = format!("{}_{}", prefix, flag.name.to_uppercase());
            self.raw(&format!("#define {} (({})1 << {})\n", flag_name, c_type, flag.position));
        }
    }

    // ---- Bitset ----

    fn emit_bitset(&mut self, b: &ResolvedBitset) {
        let wire_type = bitset_wire_c_type(b.total_bits);
        self.raw(&format!("/* bitset {} ({} bits) */\n", b.name, b.total_bits));
        self.raw(&format!("typedef struct {} {{\n", b.name));
        for f in &b.fields {
            let field_type = bitfield_c_type(f.bit_width);
            let field_name = naming::escape_keyword(&f.name, naming::TargetLang::C);
            self.raw(&format!("    {} {};\n", field_type, field_name));
        }
        self.raw(&format!("}} {};\n\n", b.name));

        // Pack function
        self.raw(&format!(
            "static inline {} {}_pack(const {} *val) {{\n",
            wire_type, b.name, b.name
        ));
        self.raw(&format!("    {} packed = 0;\n", wire_type));
        let mut bit_offset = 0u32;
        for f in &b.fields {
            let mask = (1u64 << f.bit_width) - 1;
            let field_name = naming::escape_keyword(&f.name, naming::TargetLang::C);
            self.raw(&format!(
                "    packed |= (({})val->{} & 0x{:X}) << {};\n",
                wire_type, field_name, mask, bit_offset
            ));
            bit_offset += f.bit_width;
        }
        self.raw("    return packed;\n}\n\n");

        // Unpack function
        self.raw(&format!(
            "static inline void {}_unpack({} packed, {} *val) {{\n",
            b.name, wire_type, b.name
        ));
        let mut bit_offset = 0u32;
        for f in &b.fields {
            let mask = (1u64 << f.bit_width) - 1;
            let field_type = bitfield_c_type(f.bit_width);
            let field_name = naming::escape_keyword(&f.name, naming::TargetLang::C);
            self.raw(&format!(
                "    val->{} = ({})((packed >> {}) & 0x{:X});\n",
                field_name, field_type, bit_offset, mask
            ));
            bit_offset += f.bit_width;
        }
        self.raw("}\n");
    }

    // ---- Union ----

    fn emit_union_typedef(&mut self, u: &ResolvedUnion) {
        let disc_c = self.type_to_c_base(&u.discriminant_type);
        self.raw(&format!("struct {} {{\n", u.name));
        self.raw(&format!("    {} _d;\n", disc_c));
        self.raw("    union {\n");
        for case in &u.cases {
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let field_decl = self.type_to_c_declaration(&case.member.resolved_type, &case_name);
            self.raw(&format!("        {};\n", field_decl));
        }
        if let Some(dc) = &u.default_case {
            let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
            let field_decl = self.type_to_c_declaration(&dc.resolved_type, &dc_name);
            self.raw(&format!("        {};\n", field_decl));
        }
        self.raw("    } _u;\n");
        self.raw("};\n\n");
    }

    fn emit_union_functions(&mut self, u: &ResolvedUnion) {
        if self.opts.string_mode == StringMode::Pointer && self.union_needs_cleanup(u) {
            self.emit_union_cleanup(u);
            self.raw("\n");
        }

        let needs_union_dh = !matches!(u.extensibility, ExtensibilityKind::Final);

        // serialize_fields (for nested union support - no encapsulation)
        self.raw(&format!(
            "static inline void {}_serialize_fields(\n    Int2DdsCdrWriter *_w,\n    const {} *val)\n{{\n",
            u.name, u.name
        ));
        self.raw("    Int2DdsCdrWriter w = *_w;\n");
        if needs_union_dh {
            self.raw("    size_t _u_dh = 0;\n");
            self.raw("    if (w.xcdr2) { int2dds_cdr_write_dheader_begin(&w, &_u_dh); }\n");
        }
        self.emit_write_field_indented(&u.discriminant_type, "val->_d", "    ");
        self.raw("    switch (val->_d) {\n");
        for case in &u.cases {
            for label in &case.labels {
                self.raw(&format!("    case {}:\n", self.union_label_c(label)));
            }
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let accessor = format!("val->_u.{}", case_name);
            self.emit_write_field_indented(&case.member.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        if let Some(dc) = &u.default_case {
            self.raw("    default:\n");
            let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
            let accessor = format!("val->_u.{}", dc_name);
            self.emit_write_field_indented(&dc.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        self.raw("    }\n");
        if needs_union_dh {
            self.raw("    if (w.xcdr2) { int2dds_cdr_write_dheader_finalize(&w, _u_dh); }\n");
        }
        self.raw("    *_w = w;\n}\n\n");

        // deserialize_fields (for nested union support - no encapsulation)
        self.raw(&format!(
            "static inline void {}_deserialize_fields(\n    Int2DdsCdrReader *_r,\n    {} *val_out)\n{{\n",
            u.name, u.name
        ));
        self.raw("    Int2DdsCdrReader r = *_r;\n");
        if needs_union_dh {
            self.raw("    uint32_t _u_sz = 0; size_t _u_sp = 0;\n");
            self.raw("    if (r.xcdr2) { int2dds_cdr_read_dheader(&r, &_u_sz, &_u_sp); }\n");
        }
        self.emit_read_field_indented(&u.discriminant_type, "val_out->_d", "    ");
        self.raw("    switch (val_out->_d) {\n");
        for case in &u.cases {
            for label in &case.labels {
                self.raw(&format!("    case {}:\n", self.union_label_c(label)));
            }
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let accessor = format!("val_out->_u.{}", case_name);
            self.emit_read_field_indented(&case.member.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        if let Some(dc) = &u.default_case {
            self.raw("    default:\n");
            let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
            let accessor = format!("val_out->_u.{}", dc_name);
            self.emit_read_field_indented(&dc.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        self.raw("    }\n");
        if needs_union_dh {
            self.raw("    if (r.xcdr2) { int2dds_cdr_read_dheader_end(&r, _u_sz, _u_sp); }\n");
        }
        self.raw("    *_r = r;\n}\n\n");

        // Serialize function
        self.raw(&format!(
            "static inline size_t {}_serialize_cdr(\n    const {} *val,\n    uint8_t *buf,\n    size_t capacity,\n    bool xcdr2)\n{{\n",
            u.name, u.name
        ));
        self.raw("    Int2DdsCdrWriter w;\n");
        self.raw("    int2dds_cdr_writer_init(&w, buf, capacity, true, xcdr2);\n");
        let union_ext = match u.extensibility {
            ExtensibilityKind::Final => "INT2DDS_CDR_FINAL",
            ExtensibilityKind::Appendable => "INT2DDS_CDR_APPENDABLE",
            ExtensibilityKind::Mutable => "INT2DDS_CDR_MUTABLE",
        };
        self.raw(&format!("    int2dds_cdr_write_encapsulation(&w, {});\n", union_ext));
        if needs_union_dh {
            self.raw("    size_t _u_dh = 0;\n");
            self.raw("    if (w.xcdr2) { int2dds_cdr_write_dheader_begin(&w, &_u_dh); }\n");
        }
        self.emit_write_field_indented(&u.discriminant_type, "val->_d", "    ");
        self.raw("    switch (val->_d) {\n");
        for case in &u.cases {
            for label in &case.labels {
                self.raw(&format!("    case {}:\n", self.union_label_c(label)));
            }
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let accessor = format!("val->_u.{}", case_name);
            self.emit_write_field_indented(&case.member.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        if let Some(dc) = &u.default_case {
            self.raw("    default:\n");
            let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
            let accessor = format!("val->_u.{}", dc_name);
            self.emit_write_field_indented(&dc.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        self.raw("    }\n");
        if needs_union_dh {
            self.raw("    if (w.xcdr2) { int2dds_cdr_write_dheader_finalize(&w, _u_dh); }\n");
        }
        self.raw("    return w.error == INT2DDS_CDR_OK ? int2dds_cdr_writer_size(&w) : 0;\n}\n\n");

        // Deserialize function
        self.raw(&format!(
            "static inline bool {}_deserialize_cdr(\n    const uint8_t *buf,\n    size_t len,\n    {} *val_out)\n{{\n",
            u.name, u.name
        ));
        self.raw("    Int2DdsCdrReader r;\n");
        self.raw("    if (int2dds_cdr_reader_init(&r, buf, len) != INT2DDS_CDR_OK)\n        return false;\n");
        if needs_union_dh {
            self.raw("    uint32_t _u_sz = 0; size_t _u_sp = 0;\n");
            self.raw("    if (r.xcdr2) { int2dds_cdr_read_dheader(&r, &_u_sz, &_u_sp); }\n");
        }
        self.emit_read_field_indented(&u.discriminant_type, "val_out->_d", "    ");
        self.raw("    switch (val_out->_d) {\n");
        for case in &u.cases {
            for label in &case.labels {
                self.raw(&format!("    case {}:\n", self.union_label_c(label)));
            }
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let accessor = format!("val_out->_u.{}", case_name);
            self.emit_read_field_indented(&case.member.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        if let Some(dc) = &u.default_case {
            self.raw("    default:\n");
            let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
            let accessor = format!("val_out->_u.{}", dc_name);
            self.emit_read_field_indented(&dc.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        self.raw("    }\n");
        if needs_union_dh {
            self.raw("    if (r.xcdr2) { int2dds_cdr_read_dheader_end(&r, _u_sz, _u_sp); }\n");
        }
        self.raw("    return int2dds_cdr_reader_error(&r) == INT2DDS_CDR_OK;\n}\n");
    }

    fn union_label_c(&self, label: &ResolvedUnionLabel) -> String {
        match label {
            ResolvedUnionLabel::Int(v) => v.to_string(),
            ResolvedUnionLabel::Bool(v) => if *v { "true" } else { "false" }.to_string(),
            ResolvedUnionLabel::Ident(name) => name.clone(),
        }
    }

    // ---- Struct ----

    fn emit_struct_header(&mut self, s: &ResolvedStruct) {
        let ext_str = match s.extensibility {
            ExtensibilityKind::Final => "FINAL",
            ExtensibilityKind::Appendable => "APPENDABLE",
            ExtensibilityKind::Mutable => "MUTABLE",
        };
        self.raw(&format!(
            "/* ========================================================================\n * Type: {}\n * Extensibility: {}\n * ======================================================================== */\n\n",
            s.name, ext_str
        ));
    }

    fn emit_struct_functions(&mut self, s: &ResolvedStruct) {
        // Memory management functions (only for Pointer mode)
        if self.opts.string_mode == StringMode::Pointer {
            self.emit_struct_init(s);
            self.raw("\n");

            // Only emit cleanup if struct has strings
            if self.struct_needs_cleanup(s) {
                self.emit_struct_cleanup(s);
                self.raw("\n");
            }
        }

        // serialize_fields / deserialize_fields (for nested struct support)
        self.emit_serialize_fields_fn(s);
        self.raw("\n");

        self.emit_deserialize_fields_fn(s);
        self.raw("\n");

        // serialize_cdr
        self.emit_serialize_cdr(s);
        self.raw("\n");

        // writer-anchored serialize: xcdr2 follows the writer's effective DataRepresentation
        self.emit_serialize_for_fn(s);
        self.raw("\n");

        // deserialize_cdr
        self.emit_deserialize_cdr(s);
        self.raw("\n");

        // type_info builder (for DDS-XTypes discovery)
        self.emit_type_info_fn(s);
        self.raw("\n");

        // create_topic helper (extensibility carried by the type, no arg)
        self.emit_create_topic_fn(s);
    }

    fn emit_struct_typedef(&mut self, s: &ResolvedStruct) {
        self.raw(&format!("struct {} {{\n", s.name));
        // If there's a base type, insert parent as first member
        if let Some(base) = &s.base_type {
            let simple = base.rsplit("::").next().unwrap_or(base);
            self.raw(&format!("    {} parent;\n", simple));
        }
        for m in &s.members {
            let field_decl = self.field_declaration(m);
            self.raw(&format!("    {};\n", field_decl));
        }
        self.raw("};\n");
    }

    fn field_declaration(&self, m: &ResolvedMember) -> String {
        let escaped = naming::escape_keyword(&m.name, naming::TargetLang::C);
        if m.is_external {
            // External fields are pointers in C.
            // For aggregate types (Sequence, Map) we need to generate a pointer
            // to the anonymous struct rather than void*.
            match &m.resolved_type {
                ResolvedType::Sequence { .. } | ResolvedType::Map { .. } => {
                    // Reuse the normal declaration with a pointer-prefixed name
                    // e.g. "struct { int32_t* data; uint32_t length; } *field_name"
                    self.type_to_c_declaration(&m.resolved_type, &format!("*{}", escaped))
                }
                _ => {
                    let base = self.type_to_c_base(&m.resolved_type);
                    format!("{}* {}", base, escaped)
                }
            }
        } else {
            self.type_to_c_declaration(&m.resolved_type, &escaped)
        }
    }

    /// IDL constants map to `#define` (classic OMG IDL-to-C mapping).
    fn emit_constants(&mut self) {
        if self.model.constants.is_empty() {
            return;
        }
        for c in &self.model.constants {
            let name = naming::escape_keyword(&c.name, naming::TargetLang::C);
            self.raw(&format!("#define {} {}\n", name, c_const_value(&c.value)));
        }
        self.raw("\n");
    }

    fn type_to_c_declaration(&self, ty: &ResolvedType, name: &str) -> String {
        match ty {
            ResolvedType::Bool => format!("bool {}", name),
            ResolvedType::U8 | ResolvedType::UInt8 => format!("uint8_t {}", name),
            ResolvedType::I8 => format!("int8_t {}", name),
            ResolvedType::I16 => format!("int16_t {}", name),
            ResolvedType::U16 => format!("uint16_t {}", name),
            ResolvedType::I32 => format!("int32_t {}", name),
            ResolvedType::U32 => format!("uint32_t {}", name),
            ResolvedType::I64 => format!("int64_t {}", name),
            ResolvedType::U64 => format!("uint64_t {}", name),
            ResolvedType::F32 => format!("float {}", name),
            ResolvedType::F64 => format!("double {}", name),
            ResolvedType::Char => format!("char {}", name),
            ResolvedType::WChar => format!("uint16_t {}", name),
            ResolvedType::String { bound } => match self.opts.string_mode {
                StringMode::FixedArray => {
                    let size = bound.unwrap_or(self.opts.default_string_bound) + 1;
                    format!("char {}[{}]", name, size)
                }
                StringMode::Pointer => format!("char* {}", name),
            },
            ResolvedType::WString { bound } => {
                let size = bound.unwrap_or(self.opts.default_string_bound) + 1;
                format!("uint16_t {}[{}]", name, size)
            }
            ResolvedType::Sequence { element, bound } => {
                // Special handling for sequence<string> in FixedArray mode:
                // each element is char[size], so we need char data[N][size] (bounded)
                // or char (*data)[size] (unbounded pointer-to-array).
                if let ResolvedType::String { bound: str_bound } = element.as_ref() {
                    if self.opts.string_mode == StringMode::FixedArray {
                        let str_size = str_bound.unwrap_or(self.opts.default_string_bound) + 1;
                        return if let Some(max) = bound {
                            format!(
                                "struct {{ char data[{}][{}]; uint32_t length; }} {}",
                                max, str_size, name
                            )
                        } else {
                            format!(
                                "struct {{ char (*data)[{}]; uint32_t length; }} {}",
                                str_size, name
                            )
                        };
                    }
                }
                let elem_c = self.type_to_c_base(element);
                if let Some(max) = bound {
                    // Bounded: inline array + length
                    format!("struct {{ {} data[{}]; uint32_t length; }} {}", elem_c, max, name)
                } else {
                    // Unbounded: pointer + length
                    format!("struct {{ {}* data; uint32_t length; }} {}", elem_c, name)
                }
            }
            ResolvedType::Array { element, size } => {
                // Declare through the element rather than off `type_to_c_base`: the element
                // may itself need the declarator (a nested array wants another `[n]`, a string
                // its char buffer, a sequence its struct wrapper), and only this function
                // knows where each of those puts the name.
                self.type_to_c_declaration(element, &format!("{}[{}]", name, size))
            }
            ResolvedType::Map { key, value, bound } => {
                let key_decl = self.map_member_decl(key, "keys", bound);
                let val_decl = self.map_member_decl(value, "values", bound);
                format!("struct {{ {}; {}; uint32_t length; }} {}", key_decl, val_decl, name)
            }
            ResolvedType::Struct(type_name)
            | ResolvedType::Enum(type_name)
            | ResolvedType::Bitmask(type_name) => {
                let simple = type_name.rsplit("::").next().unwrap_or(type_name);
                format!("{} {}", simple, name)
            }
        }
    }

    fn type_to_c_base(&self, ty: &ResolvedType) -> String {
        match ty {
            ResolvedType::Bool => "bool".to_string(),
            ResolvedType::U8 | ResolvedType::UInt8 => "uint8_t".to_string(),
            ResolvedType::I8 => "int8_t".to_string(),
            ResolvedType::I16 => "int16_t".to_string(),
            ResolvedType::U16 => "uint16_t".to_string(),
            ResolvedType::I32 => "int32_t".to_string(),
            ResolvedType::U32 => "uint32_t".to_string(),
            ResolvedType::I64 => "int64_t".to_string(),
            ResolvedType::U64 => "uint64_t".to_string(),
            ResolvedType::F32 => "float".to_string(),
            ResolvedType::F64 => "double".to_string(),
            ResolvedType::Char => "char".to_string(),
            ResolvedType::WChar => "uint16_t".to_string(),
            ResolvedType::String { .. } => match self.opts.string_mode {
                StringMode::FixedArray => {
                    // Base type for string in FixedArray mode.
                    // Note: sequence<string> is handled specially in type_to_c_declaration.
                    "char".to_string()
                }
                StringMode::Pointer => "char*".to_string(),
            },
            ResolvedType::WString { .. } => "uint16_t".to_string(),
            ResolvedType::Struct(name) | ResolvedType::Enum(name) | ResolvedType::Bitmask(name) => {
                name.rsplit("::").next().unwrap_or(name).to_string()
            }
            _ => "void".to_string(), // shouldn't happen in base context
        }
    }

    // ---- Fields serialize/deserialize (for nested struct support) ----
    //
    // These standalone functions allow a parent struct to serialize/deserialize
    // a nested struct field using an existing writer/reader.
    // The copy-in/copy-out pattern (`w = *_w` ... `*_w = w`) lets us reuse the
    // same field-emit code that references a local `w`/`r`.

    fn emit_serialize_fields_fn(&mut self, s: &ResolvedStruct) {
        self.raw(&format!(
            "static inline void {}_serialize_fields(\n    Int2DdsCdrWriter *_w,\n    const {} *val)\n{{\n",
            s.name, s.name
        ));
        self.raw("    Int2DdsCdrWriter w = *_w;\n");

        match s.extensibility {
            ExtensibilityKind::Final => {
                self.emit_serialize_fields(s, "val");
            }
            ExtensibilityKind::Appendable => {
                // Conditionally write DHEADER based on writer mode (XCDR2 vs XCDR1)
                self.raw("    size_t dh = 0;\n");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_begin(&w, &dh);\n");
                self.raw("    }\n");
                self.emit_serialize_fields(s, "val");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_finalize(&w, dh);\n");
                self.raw("    }\n");
            }
            ExtensibilityKind::Mutable => {
                self.raw("    size_t dh = 0;\n");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_begin(&w, &dh);\n");
                self.raw("    }\n");
                self.emit_serialize_fields_mutable(s, "val");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_finalize(&w, dh);\n");
                self.raw("    } else {\n");
                self.raw("        int2dds_cdr_write_pid_sentinel(&w);\n");
                self.raw("    }\n");
            }
        }

        self.raw("    *_w = w;\n}\n");
    }

    fn emit_deserialize_fields_fn(&mut self, s: &ResolvedStruct) {
        self.raw(&format!(
            "static inline void {}_deserialize_fields(\n    Int2DdsCdrReader *_r,\n    {} *val_out)\n{{\n",
            s.name, s.name
        ));
        self.raw("    Int2DdsCdrReader r = *_r;\n");

        match s.extensibility {
            ExtensibilityKind::Final => {
                self.emit_deserialize_fields(s, "val_out");
            }
            ExtensibilityKind::Appendable => {
                // Conditionally read DHEADER based on reader mode (XCDR2 vs XCDR1)
                self.raw("    uint32_t obj_size = 0;\n    size_t start_pos = 0;\n");
                self.raw("    if (r.xcdr2) {\n");
                self.raw("        int2dds_cdr_read_dheader(&r, &obj_size, &start_pos);\n");
                self.raw("    }\n");
                self.emit_deserialize_fields(s, "val_out");
                self.raw("    if (r.xcdr2) {\n");
                self.raw("        int2dds_cdr_read_dheader_end(&r, obj_size, start_pos);\n");
                self.raw("    }\n");
            }
            ExtensibilityKind::Mutable => {
                self.raw("    memset(val_out, 0, sizeof(*val_out));\n");
                self.emit_deserialize_fields_mutable(s, "val_out");
            }
        }

        self.raw("    *_r = r;\n}\n");
    }

    // ---- Serialize CDR ----

    fn emit_serialize_cdr(&mut self, s: &ResolvedStruct) {
        let ext_int = match s.extensibility {
            ExtensibilityKind::Final => "INT2DDS_CDR_FINAL",
            ExtensibilityKind::Appendable => "INT2DDS_CDR_APPENDABLE",
            ExtensibilityKind::Mutable => "INT2DDS_CDR_MUTABLE",
        };

        self.raw(&format!(
            "static inline size_t {}_serialize_cdr(\n    const {} *val,\n    uint8_t *buf,\n    size_t capacity,\n    bool xcdr2)\n{{\n",
            s.name, s.name
        ));

        self.raw("    Int2DdsCdrWriter w;\n");
        self.raw("    int2dds_cdr_writer_init(&w, buf, capacity, true, xcdr2);\n");
        self.raw(&format!("    int2dds_cdr_write_encapsulation(&w, {});\n", ext_int));

        match s.extensibility {
            ExtensibilityKind::Final => {
                self.emit_serialize_fields(s, "val");
            }
            ExtensibilityKind::Appendable => {
                self.raw("    size_t dh = 0;\n");
                self.raw("    if (xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_begin(&w, &dh);\n");
                self.raw("    }\n");
                self.emit_serialize_fields(s, "val");
                self.raw("    if (xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_finalize(&w, dh);\n");
                self.raw("    }\n");
            }
            ExtensibilityKind::Mutable => {
                // XCDR2: DHEADER + EMHEADER (DHEADER-bounded, no sentinel)
                // XCDR1: PL_CDR parameter list (PID headers, sentinel-terminated)
                self.raw("    size_t dh = 0;\n");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_begin(&w, &dh);\n");
                self.raw("    }\n");
                self.emit_serialize_fields_mutable(s, "val");
                self.raw("    if (w.xcdr2) {\n");
                self.raw("        int2dds_cdr_write_dheader_finalize(&w, dh);\n");
                self.raw("    } else {\n");
                self.raw("        int2dds_cdr_write_pid_sentinel(&w);\n");
                self.raw("    }\n");
            }
        }

        self.raw("    return w.error == INT2DDS_CDR_OK ? int2dds_cdr_writer_size(&w) : 0;\n}\n");
    }

    fn emit_serialize_for_fn(&mut self, s: &ResolvedStruct) {
        self.raw(&format!(
            "static inline size_t {}_serialize_for(\n    const Int2DdsDataWriter *writer,\n    const {} *val,\n    uint8_t *buf,\n    size_t capacity)\n{{\n",
            s.name, s.name
        ));
        self.raw(&format!(
            "    return {}_serialize_cdr(val, buf, capacity,\n        int2dds_datawriter_data_representation(writer) == INT2DDS_QOS_DATA_REPR_XCDR2);\n}}\n",
            s.name
        ));
    }

    fn make_field_accessor(&self, m: &ResolvedMember, prefix: &str, field_name: &str) -> String {
        if m.is_external {
            let pass_through = matches!(
                &m.resolved_type,
                ResolvedType::String { .. } if self.opts.string_mode == StringMode::FixedArray
            ) || matches!(&m.resolved_type, ResolvedType::WString { .. });
            if pass_through {
                format!("{}->{}", prefix, field_name)
            } else {
                format!("(*{}->{})", prefix, field_name)
            }
        } else {
            format!("{}->{}", prefix, field_name)
        }
    }

    fn emit_serialize_fields(&mut self, s: &ResolvedStruct, prefix: &str) {
        // Inline parent fields (flat) — a single outer DHEADER bounds the whole
        // struct including inherited fields, matching Rust/C#. Calling
        // {Parent}_serialize_fields would emit a nested DHEADER and desync with Rust.
        if let Some(base) = &s.base_type {
            let simple = base.rsplit("::").next().unwrap_or(base);
            if let Some(parent_struct) =
                self.model.structs.iter().find(|st| st.name == simple).cloned()
            {
                let parent_var = format!("_p_{}", simple.to_lowercase());
                self.raw(&format!("    const {} *{} = &{}->parent;\n", simple, parent_var, prefix));
                self.emit_serialize_fields(&parent_struct, &parent_var);
            }
        }
        for m in &s.members {
            let field_name = naming::escape_keyword(&m.name, naming::TargetLang::C);
            let accessor = self.make_field_accessor(m, prefix, &field_name);
            self.emit_write_field(&m.resolved_type, &accessor);
        }
    }

    fn emit_serialize_fields_mutable(&mut self, s: &ResolvedStruct, prefix: &str) {
        for (i, m) in s.members.iter().enumerate() {
            let id = m.member_id.unwrap_or(i as u32);
            let mu = if m.must_understand { "true" } else { "false" };
            let field_name = naming::escape_keyword(&m.name, naming::TargetLang::C);
            let accessor = self.make_field_accessor(m, prefix, &field_name);
            self.raw("    {\n");
            self.raw("        size_t em;\n");
            self.raw("        if (w.xcdr2) {\n");
            self.raw(&format!(
                "            int2dds_cdr_write_emheader_begin(&w, {}, {}, &em);\n",
                id, mu
            ));
            self.raw("        } else {\n");
            self.raw(&format!("            int2dds_cdr_write_pid_begin(&w, {}, &em);\n", id));
            self.raw("        }\n");
            self.emit_write_field_indented(&m.resolved_type, &accessor, "        ");
            self.raw("        if (w.xcdr2) {\n");
            self.raw("            int2dds_cdr_write_emheader_finalize(&w, em);\n");
            self.raw("        } else {\n");
            self.raw(&format!(
                "            int2dds_cdr_write_pid_finalize(&w, {}, {}, em);\n",
                id, mu
            ));
            self.raw("        }\n");
            self.raw("    }\n");
        }
    }

    fn emit_write_field(&mut self, ty: &ResolvedType, accessor: &str) {
        self.emit_write_field_indented(ty, accessor, "    ");
    }

    fn emit_write_field_indented(&mut self, ty: &ResolvedType, accessor: &str, indent: &str) {
        match ty {
            ResolvedType::Bool => {
                self.raw(&format!("{}int2dds_cdr_write_bool(&w, {});\n", indent, accessor));
            }
            ResolvedType::U8 | ResolvedType::UInt8 => {
                self.raw(&format!("{}int2dds_cdr_write_u8(&w, {});\n", indent, accessor));
            }
            ResolvedType::I8 => {
                self.raw(&format!("{}int2dds_cdr_write_i8(&w, {});\n", indent, accessor));
            }
            ResolvedType::I16 => {
                self.raw(&format!("{}int2dds_cdr_write_i16(&w, {});\n", indent, accessor));
            }
            ResolvedType::U16 | ResolvedType::WChar => {
                self.raw(&format!("{}int2dds_cdr_write_u16(&w, {});\n", indent, accessor));
            }
            ResolvedType::I32 => {
                self.raw(&format!("{}int2dds_cdr_write_i32(&w, {});\n", indent, accessor));
            }
            ResolvedType::U32 => {
                self.raw(&format!("{}int2dds_cdr_write_u32(&w, {});\n", indent, accessor));
            }
            ResolvedType::I64 => {
                self.raw(&format!("{}int2dds_cdr_write_i64(&w, {});\n", indent, accessor));
            }
            ResolvedType::U64 => {
                self.raw(&format!("{}int2dds_cdr_write_u64(&w, {});\n", indent, accessor));
            }
            ResolvedType::F32 => {
                self.raw(&format!("{}int2dds_cdr_write_f32(&w, {});\n", indent, accessor));
            }
            ResolvedType::F64 => {
                self.raw(&format!("{}int2dds_cdr_write_f64(&w, {});\n", indent, accessor));
            }
            ResolvedType::Char => {
                self.raw(&format!("{}int2dds_cdr_write_u8(&w, (uint8_t){});\n", indent, accessor));
            }
            ResolvedType::String { .. } => {
                self.raw(&format!("{}int2dds_cdr_write_string(&w, {});\n", indent, accessor));
            }
            ResolvedType::WString { bound } => {
                // Write as sequence of uint16_t
                let len = bound.unwrap_or(self.opts.default_string_bound);
                self.raw(&format!("{}{{ uint32_t _wlen = 0;\n", indent));
                self.raw(&format!(
                    "{}while (_wlen < {} && {}[_wlen]) _wlen++;\n",
                    indent, len, accessor
                ));
                self.raw(&format!("{}int2dds_cdr_write_u32(&w, _wlen);\n", indent));
                self.raw(&format!("{}for (uint32_t _wi = 0; _wi < _wlen; _wi++) int2dds_cdr_write_u16(&w, {}[_wi]);\n", indent, accessor));
                self.raw(&format!("{}}}\n", indent));
            }
            ResolvedType::Enum(_) => {
                self.raw(&format!(
                    "{}int2dds_cdr_write_enum(&w, (int32_t){});\n",
                    indent, accessor
                ));
            }
            ResolvedType::Bitmask(bitmask_name) => {
                let bit_bound = self.find_bitmask(bitmask_name).map(|b| b.bit_bound).unwrap_or(32);
                let (write_fn, cast_type) = bitmask_cdr_write_info(bit_bound);
                self.raw(&format!("{}{}(&w, ({}){});\n", indent, write_fn, cast_type, accessor));
            }
            ResolvedType::Sequence { element, .. } => {
                let needs_dh = Self::sequence_element_needs_dheader(element);
                if needs_dh {
                    self.raw(&format!("{}{{ size_t _seq_dh = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_begin(&w, &_seq_dh); }}\n",
                        indent
                    ));
                }
                self.raw(&format!(
                    "{}int2dds_cdr_write_seq_header(&w, {}.length);\n",
                    indent, accessor
                ));
                if let Some(kind) = self.bulk_element(element) {
                    let data = format!("{}.data", accessor);
                    let count = format!("{}.length", accessor);
                    self.emit_bulk_write(kind, &data, &count, indent);
                } else {
                    self.raw(&format!(
                        "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                        indent, accessor
                    ));
                    let elem_accessor = format!("{}.data[_i]", accessor);
                    self.emit_write_field_indented(
                        element,
                        &elem_accessor,
                        &format!("{}    ", indent),
                    );
                    self.raw(&format!("{}}}\n", indent));
                }
                if needs_dh {
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_finalize(&w, _seq_dh); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Array { .. } => {
                // One array of the base type (7.4.3.4): frame once above every dimension,
                // then walk them with distinct indices. Recursing per dimension instead
                // would emit a DHEADER per row and reuse `_i` at every level.
                let (dims, base) = flatten_array(ty);
                let needs_dh = Self::array_needs_dheader(base);
                if needs_dh {
                    self.raw(&format!("{}{{ size_t _arr_dh = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_begin(&w, &_arr_dh); }}\n",
                        indent
                    ));
                }
                // A bulk write covers the innermost dimension, so only the outer ones loop.
                let bulk = self.bulk_element(base);
                let loops = if bulk.is_some() { dims.len() - 1 } else { dims.len() };
                let mut acc = accessor.to_string();
                let mut ind = indent.to_string();
                for (d, n) in dims.iter().take(loops).enumerate() {
                    self.raw(&format!(
                        "{}for (uint32_t _i{} = 0; _i{} < {}; _i{}++) {{\n",
                        ind, d, d, n, d
                    ));
                    acc = format!("{}[_i{}]", acc, d);
                    ind.push_str("    ");
                }
                match bulk {
                    Some(kind) => {
                        self.emit_bulk_write(kind, &acc, &dims[dims.len() - 1].to_string(), &ind)
                    }
                    None => self.emit_write_field_indented(base, &acc, &ind),
                }
                for _ in 0..loops {
                    ind.truncate(ind.len() - 4);
                    self.raw(&format!("{}}}\n", ind));
                }
                if needs_dh {
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_finalize(&w, _arr_dh); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Map { key, value, .. } => {
                let needs_dh = Self::sequence_element_needs_dheader(key)
                    || Self::sequence_element_needs_dheader(value);
                if needs_dh {
                    self.raw(&format!("{}{{ size_t _map_dh = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_begin(&w, &_map_dh); }}\n",
                        indent
                    ));
                }
                self.raw(&format!(
                    "{}int2dds_cdr_write_seq_header(&w, {}.length);\n",
                    indent, accessor
                ));
                self.raw(&format!(
                    "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                    indent, accessor
                ));
                let key_acc = format!("{}.keys[_i]", accessor);
                let val_acc = format!("{}.values[_i]", accessor);
                self.emit_write_field_indented(key, &key_acc, &format!("{}    ", indent));
                self.emit_write_field_indented(value, &val_acc, &format!("{}    ", indent));
                self.raw(&format!("{}}}\n", indent));
                if needs_dh {
                    self.raw(&format!(
                        "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_finalize(&w, _map_dh); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Struct(type_name) => {
                let simple = type_name.rsplit("::").next().unwrap_or(type_name);
                // Check if this is actually a bitset type
                if let Some(bitset) = self.find_bitset(type_name).cloned() {
                    let wire_type = bitset_wire_c_type(bitset.total_bits);
                    let write_fn = match bitset.total_bits {
                        0..=8 => "int2dds_cdr_write_u8",
                        9..=16 => "int2dds_cdr_write_u16",
                        17..=32 => "int2dds_cdr_write_u32",
                        _ => "int2dds_cdr_write_u64",
                    };
                    self.raw(&format!(
                        "{}{}(&w, ({})({}_pack(&{})));\n",
                        indent, write_fn, wire_type, simple, accessor
                    ));
                } else {
                    let needs_dh = self.struct_needs_member_dheader(type_name);
                    if needs_dh {
                        self.raw(&format!("{}{{ size_t _mbr_dh = 0;\n", indent));
                        self.raw(&format!(
                            "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_begin(&w, &_mbr_dh); }}\n",
                            indent
                        ));
                    }
                    self.raw(&format!(
                        "{}{}_serialize_fields(&w, &{});\n",
                        indent, simple, accessor
                    ));
                    if needs_dh {
                        self.raw(&format!(
                            "{}if (w.xcdr2) {{ int2dds_cdr_write_dheader_finalize(&w, _mbr_dh); }}\n",
                            indent
                        ));
                        self.raw(&format!("{}}}\n", indent));
                    }
                }
            }
        }
    }

    // ---- Deserialize CDR ----

    fn emit_deserialize_cdr(&mut self, s: &ResolvedStruct) {
        self.raw(&format!(
            "static inline bool {}_deserialize_cdr(\n    const uint8_t *buf,\n    size_t len,\n    {} *val_out)\n{{\n",
            s.name, s.name
        ));
        self.raw("    Int2DdsCdrReader r;\n");
        self.raw(
            "    if (int2dds_cdr_reader_init(&r, buf, len) != INT2DDS_CDR_OK)\n        return false;\n",
        );

        match s.extensibility {
            ExtensibilityKind::Final => {
                self.emit_deserialize_fields(s, "val_out");
            }
            ExtensibilityKind::Appendable => {
                // Auto-detect XCDR1 vs XCDR2 from encapsulation header (set by reader_init)
                self.raw("    uint32_t obj_size = 0;\n    size_t start_pos = 0;\n");
                self.raw("    if (r.xcdr2) {\n");
                self.raw("        int2dds_cdr_read_dheader(&r, &obj_size, &start_pos);\n");
                self.raw("    }\n");
                self.emit_deserialize_fields(s, "val_out");
                self.raw("    if (r.xcdr2) {\n");
                self.raw("        int2dds_cdr_read_dheader_end(&r, obj_size, start_pos);\n");
                self.raw("    }\n");
            }
            ExtensibilityKind::Mutable => {
                self.raw("    memset(val_out, 0, sizeof(*val_out));\n");
                self.emit_deserialize_fields_mutable(s, "val_out");
            }
        }

        self.raw("    return int2dds_cdr_reader_error(&r) == INT2DDS_CDR_OK;\n}\n");
    }

    fn emit_deserialize_fields(&mut self, s: &ResolvedStruct, prefix: &str) {
        // Inline parent fields (flat) — see emit_serialize_fields.
        if let Some(base) = &s.base_type {
            let simple = base.rsplit("::").next().unwrap_or(base);
            if let Some(parent_struct) =
                self.model.structs.iter().find(|st| st.name == simple).cloned()
            {
                let parent_var = format!("_p_{}", simple.to_lowercase());
                self.raw(&format!("    {} *{} = &{}->parent;\n", simple, parent_var, prefix));
                self.emit_deserialize_fields(&parent_struct, &parent_var);
            }
        }
        for m in &s.members {
            let field_name = naming::escape_keyword(&m.name, naming::TargetLang::C);
            let accessor = self.make_field_accessor(m, prefix, &field_name);
            self.emit_read_field(&m.resolved_type, &accessor);
        }
    }

    fn emit_deserialize_fields_mutable(&mut self, s: &ResolvedStruct, prefix: &str) {
        self.raw("    if (r.xcdr2) {\n");
        self.raw("        uint32_t obj_size;\n        size_t start_pos;\n");
        self.raw("        int2dds_cdr_read_dheader(&r, &obj_size, &start_pos);\n");
        self.raw("        size_t _d_end = start_pos + obj_size;\n");
        self.raw("        while (int2dds_cdr_reader_position(&r) < _d_end) {\n");
        self.raw("            uint32_t mid, dlen;\n            bool mu;\n");
        self.raw(
            "            if (!int2dds_cdr_read_emheader(&r, &mid, &dlen, &mu))\n                break;\n",
        );
        self.emit_mutable_member_switch(s, prefix, "            ");
        self.raw("        }\n");
        self.raw("        int2dds_cdr_read_dheader_end(&r, obj_size, start_pos);\n");
        self.raw("    } else {\n");
        self.raw("        for (;;) {\n");
        self.raw("            uint32_t mid, dlen;\n            bool sen;\n");
        self.raw(
            "            if (!int2dds_cdr_read_pid_header(&r, &mid, &dlen, &sen) || sen)\n                break;\n",
        );
        self.raw("            size_t mstart = int2dds_cdr_reader_position(&r);\n");
        self.emit_mutable_member_switch(s, prefix, "            ");
        self.raw("            size_t mused = int2dds_cdr_reader_position(&r) - mstart;\n");
        self.raw("            if (mused < dlen) {\n");
        self.raw("                int2dds_cdr_skip_bytes(&r, dlen - mused);\n");
        self.raw("            }\n");
        self.raw("        }\n");
        self.raw("    }\n");
    }

    fn emit_mutable_member_switch(&mut self, s: &ResolvedStruct, prefix: &str, indent: &str) {
        self.raw(&format!("{}switch (mid) {{\n", indent));
        for (i, m) in s.members.iter().enumerate() {
            let id = m.member_id.unwrap_or(i as u32);
            let field_name = naming::escape_keyword(&m.name, naming::TargetLang::C);
            let accessor = self.make_field_accessor(m, prefix, &field_name);
            self.raw(&format!("{}case {}:\n", indent, id));
            self.emit_read_field_indented(&m.resolved_type, &accessor, &format!("{}    ", indent));
            self.raw(&format!("{}    break;\n", indent));
        }
        self.raw(&format!("{}default:\n", indent));
        self.raw(&format!("{}    int2dds_cdr_skip_bytes(&r, dlen);\n", indent));
        self.raw(&format!("{}    break;\n", indent));
        self.raw(&format!("{}}}\n", indent));
    }

    fn emit_read_field(&mut self, ty: &ResolvedType, accessor: &str) {
        self.emit_read_field_indented(ty, accessor, "    ");
    }

    fn emit_read_field_indented(&mut self, ty: &ResolvedType, accessor: &str, indent: &str) {
        match ty {
            ResolvedType::Bool => {
                self.raw(&format!("{}int2dds_cdr_read_bool(&r, &{});\n", indent, accessor));
            }
            ResolvedType::U8 | ResolvedType::UInt8 => {
                self.raw(&format!("{}int2dds_cdr_read_u8(&r, &{});\n", indent, accessor));
            }
            ResolvedType::I8 => {
                self.raw(&format!("{}int2dds_cdr_read_i8(&r, &{});\n", indent, accessor));
            }
            ResolvedType::I16 => {
                self.raw(&format!("{}int2dds_cdr_read_i16(&r, &{});\n", indent, accessor));
            }
            ResolvedType::U16 | ResolvedType::WChar => {
                self.raw(&format!("{}int2dds_cdr_read_u16(&r, &{});\n", indent, accessor));
            }
            ResolvedType::I32 => {
                self.raw(&format!("{}int2dds_cdr_read_i32(&r, &{});\n", indent, accessor));
            }
            ResolvedType::U32 => {
                self.raw(&format!("{}int2dds_cdr_read_u32(&r, &{});\n", indent, accessor));
            }
            ResolvedType::I64 => {
                self.raw(&format!("{}int2dds_cdr_read_i64(&r, &{});\n", indent, accessor));
            }
            ResolvedType::U64 => {
                self.raw(&format!("{}int2dds_cdr_read_u64(&r, &{});\n", indent, accessor));
            }
            ResolvedType::F32 => {
                self.raw(&format!("{}int2dds_cdr_read_f32(&r, &{});\n", indent, accessor));
            }
            ResolvedType::F64 => {
                self.raw(&format!("{}int2dds_cdr_read_f64(&r, &{});\n", indent, accessor));
            }
            ResolvedType::Char => {
                self.raw(&format!("{}int2dds_cdr_read_u8(&r, (uint8_t*)&{});\n", indent, accessor));
            }
            ResolvedType::String { bound } => match self.opts.string_mode {
                StringMode::FixedArray => {
                    let size = bound.unwrap_or(self.opts.default_string_bound) + 1;
                    self.raw(&format!(
                        "{}int2dds_cdr_read_string_copy(&r, {}, {}, NULL);\n",
                        indent, accessor, size
                    ));
                }
                StringMode::Pointer => {
                    // Zero-copy read, then allocate and copy
                    self.raw(&format!("{}{{ const char* _str; size_t _len;\n", indent));
                    self.raw(&format!("{}int2dds_cdr_read_string(&r, &_str, &_len);\n", indent));
                    self.raw(&format!("{}{} = (char*)malloc(_len + 1);\n", indent, accessor));
                    self.raw(&format!("{}if ({}) {{\n", indent, accessor));
                    self.raw(&format!(
                        "{}    if (_len > 0) memcpy({}, _str, _len);\n",
                        indent, accessor
                    ));
                    self.raw(&format!("{}    {}[_len] = '\\0';\n", indent, accessor));
                    self.raw(&format!("{}}}\n", indent));
                    self.raw(&format!("{}}}\n", indent));
                }
            },
            ResolvedType::WString { bound } => {
                let max_len = bound.unwrap_or(self.opts.default_string_bound);
                self.raw(&format!("{}{{ uint32_t _wlen;\n", indent));
                self.raw(&format!("{}int2dds_cdr_read_u32(&r, &_wlen);\n", indent));
                self.raw(&format!("{}if (_wlen > {}) _wlen = {};\n", indent, max_len, max_len));
                self.raw(&format!("{}for (uint32_t _wi = 0; _wi < _wlen; _wi++) int2dds_cdr_read_u16(&r, &{}[_wi]);\n", indent, accessor));
                self.raw(&format!("{}{}[_wlen] = 0;\n", indent, accessor));
                self.raw(&format!("{}}}\n", indent));
            }
            ResolvedType::Enum(_) => {
                self.raw(&format!(
                    "{}int2dds_cdr_read_enum(&r, (int32_t*)&{});\n",
                    indent, accessor
                ));
            }
            ResolvedType::Bitmask(bitmask_name) => {
                let bit_bound = self.find_bitmask(bitmask_name).map(|b| b.bit_bound).unwrap_or(32);
                let (read_fn, cast_type) = bitmask_cdr_read_info(bit_bound);
                self.raw(&format!("{}{}(&r, ({}*)&{});\n", indent, read_fn, cast_type, accessor));
            }
            ResolvedType::Sequence { element, bound } => {
                let needs_dh = Self::sequence_element_needs_dheader(element);
                if needs_dh {
                    self.raw(&format!("{}{{ uint32_t _seq_sz = 0; size_t _seq_sp = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader(&r, &_seq_sz, &_seq_sp); }}\n",
                        indent
                    ));
                }
                self.raw(&format!(
                    "{}int2dds_cdr_read_seq_header(&r, &{}.length);\n",
                    indent, accessor
                ));

                let bulk = self.bulk_element(element);
                let data = format!("{}.data", accessor);
                let count = format!("{}.length", accessor);

                // Pointer mode + unbounded: auto-allocate the data array
                if self.opts.string_mode == StringMode::Pointer && bound.is_none() {
                    let elem_c = self.type_to_c_base(element);
                    self.raw(&format!("{}if ({}.length > 0) {{\n", indent, accessor));
                    self.raw(&format!(
                        "{}    {}.data = ({}*)malloc({}.length * sizeof({}));\n",
                        indent, accessor, elem_c, accessor, elem_c
                    ));
                    self.raw(&format!("{}    if ({}.data) {{\n", indent, accessor));
                    if let Some(kind) = bulk {
                        self.emit_bulk_read(kind, &data, &count, &format!("{}        ", indent));
                    } else {
                        self.raw(&format!(
                            "{}        for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                            indent, accessor
                        ));
                        let elem_accessor = format!("{}.data[_i]", accessor);
                        self.emit_read_field_indented(
                            element,
                            &elem_accessor,
                            &format!("{}            ", indent),
                        );
                        self.raw(&format!("{}        }}\n", indent));
                    }
                    self.raw(&format!("{}    }}\n", indent));
                    self.raw(&format!("{}}}\n", indent));
                } else if let Some(kind) = bulk {
                    // Bounded or FixedArray mode: data is inline array or pre-allocated
                    self.emit_bulk_read(kind, &data, &count, indent);
                } else {
                    self.raw(&format!(
                        "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                        indent, accessor
                    ));
                    let elem_accessor = format!("{}.data[_i]", accessor);
                    self.emit_read_field_indented(
                        element,
                        &elem_accessor,
                        &format!("{}    ", indent),
                    );
                    self.raw(&format!("{}}}\n", indent));
                }
                if needs_dh {
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader_end(&r, _seq_sz, _seq_sp); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Array { .. } => {
                // Mirrors the write path: one frame over every dimension, distinct indices.
                let (dims, base) = flatten_array(ty);
                let needs_dh = Self::array_needs_dheader(base);
                if needs_dh {
                    self.raw(&format!("{}{{ uint32_t _arr_sz = 0; size_t _arr_sp = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader(&r, &_arr_sz, &_arr_sp); }}\n",
                        indent
                    ));
                }
                let bulk = self.bulk_element(base);
                let loops = if bulk.is_some() { dims.len() - 1 } else { dims.len() };
                let mut acc = accessor.to_string();
                let mut ind = indent.to_string();
                for (d, n) in dims.iter().take(loops).enumerate() {
                    self.raw(&format!(
                        "{}for (uint32_t _i{} = 0; _i{} < {}; _i{}++) {{\n",
                        ind, d, d, n, d
                    ));
                    acc = format!("{}[_i{}]", acc, d);
                    ind.push_str("    ");
                }
                match bulk {
                    Some(kind) => {
                        self.emit_bulk_read(kind, &acc, &dims[dims.len() - 1].to_string(), &ind)
                    }
                    None => self.emit_read_field_indented(base, &acc, &ind),
                }
                for _ in 0..loops {
                    ind.truncate(ind.len() - 4);
                    self.raw(&format!("{}}}\n", ind));
                }
                if needs_dh {
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader_end(&r, _arr_sz, _arr_sp); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Map { key, value, .. } => {
                let needs_dh = Self::sequence_element_needs_dheader(key)
                    || Self::sequence_element_needs_dheader(value);
                if needs_dh {
                    self.raw(&format!("{}{{ uint32_t _map_sz = 0; size_t _map_sp = 0;\n", indent));
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader(&r, &_map_sz, &_map_sp); }}\n",
                        indent
                    ));
                }
                self.raw(&format!(
                    "{}int2dds_cdr_read_seq_header(&r, &{}.length);\n",
                    indent, accessor
                ));
                self.raw(&format!(
                    "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                    indent, accessor
                ));
                let key_acc = format!("{}.keys[_i]", accessor);
                let val_acc = format!("{}.values[_i]", accessor);
                self.emit_read_field_indented(key, &key_acc, &format!("{}    ", indent));
                self.emit_read_field_indented(value, &val_acc, &format!("{}    ", indent));
                self.raw(&format!("{}}}\n", indent));
                if needs_dh {
                    self.raw(&format!(
                        "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader_end(&r, _map_sz, _map_sp); }}\n",
                        indent
                    ));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            ResolvedType::Struct(type_name) => {
                let simple = type_name.rsplit("::").next().unwrap_or(type_name);
                // Check if this is actually a bitset type
                if let Some(bitset) = self.find_bitset(type_name).cloned() {
                    let wire_type = bitset_wire_c_type(bitset.total_bits);
                    let read_fn = match bitset.total_bits {
                        0..=8 => "int2dds_cdr_read_u8",
                        9..=16 => "int2dds_cdr_read_u16",
                        17..=32 => "int2dds_cdr_read_u32",
                        _ => "int2dds_cdr_read_u64",
                    };
                    self.raw(&format!("{}{{ {} _packed;\n", indent, wire_type));
                    self.raw(&format!("{}{}(&r, &_packed);\n", indent, read_fn));
                    self.raw(&format!("{}{}_unpack(_packed, &{}); }}\n", indent, simple, accessor));
                } else {
                    let needs_dh = self.struct_needs_member_dheader(type_name);
                    if needs_dh {
                        self.raw(&format!(
                            "{}{{ uint32_t _mbr_sz = 0; size_t _mbr_sp = 0;\n",
                            indent
                        ));
                        self.raw(&format!(
                            "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader(&r, &_mbr_sz, &_mbr_sp); }}\n",
                            indent
                        ));
                    }
                    self.raw(&format!(
                        "{}{}_deserialize_fields(&r, &{});\n",
                        indent, simple, accessor
                    ));
                    if needs_dh {
                        self.raw(&format!(
                            "{}if (r.xcdr2) {{ int2dds_cdr_read_dheader_end(&r, _mbr_sz, _mbr_sp); }}\n",
                            indent
                        ));
                        self.raw(&format!("{}}}\n", indent));
                    }
                }
            }
        }
    }

    // ---- Type Info (DDS-XTypes discovery) ----

    /// How a sequence or array of `element` can be moved in one call, if at all.
    ///
    /// CDR lays same-width primitives out back to back — no inter-element padding, and no
    /// per-element transform beyond byte order — so for these element types one aligned
    /// bulk copy is byte-identical to the per-element loop. That matters for large
    /// payloads: the loop costs a bounds check per element and its loop-carried error flag
    /// blocks vectorization.
    ///
    /// Deliberately excluded:
    /// - `enum`, because the generated C type is a real `typedef enum` whose size is
    ///   implementation-defined, while the wire (and the Rust side) use int32.
    /// - `struct`, `string`, `wstring`, `map` and nested sequences/arrays, because C
    ///   in-memory layout does not match CDR layout for aggregates and variable-length
    ///   elements. Nested arrays fall through to the loop, which then recurses per
    ///   dimension and reaches this fast path on the innermost one.
    fn bulk_element(&self, element: &ResolvedType) -> Option<BulkElem> {
        match element {
            ResolvedType::Bool => Some(BulkElem::Bool),
            ResolvedType::U8 | ResolvedType::UInt8 | ResolvedType::I8 | ResolvedType::Char => {
                Some(BulkElem::Prim(1))
            }
            ResolvedType::I16 | ResolvedType::U16 | ResolvedType::WChar => Some(BulkElem::Prim(2)),
            ResolvedType::I32 | ResolvedType::U32 | ResolvedType::F32 => Some(BulkElem::Prim(4)),
            ResolvedType::I64 | ResolvedType::U64 | ResolvedType::F64 => Some(BulkElem::Prim(8)),
            ResolvedType::Bitmask(name) => {
                // emit_bitmask() declares a plain uintN_t typedef of exactly the wire width.
                let bits = self.find_bitmask(name).map(|b| b.bit_bound).unwrap_or(32);
                Some(BulkElem::Prim(match bits {
                    0..=8 => 1,
                    9..=16 => 2,
                    17..=32 => 4,
                    _ => 8,
                }))
            }
            _ => None,
        }
    }

    /// Emit the single call that writes a whole bulk-eligible element run.
    ///
    /// `boolean` needs no special case here: a valid C `bool` already holds 0 or 1, which is
    /// exactly what `int2dds_cdr_write_bool` would emit for it. Only the read side has to
    /// normalize, because there the octet comes off the wire.
    fn emit_bulk_write(&mut self, kind: BulkElem, data: &str, count: &str, indent: &str) {
        let size = match kind {
            BulkElem::Prim(size) => size,
            BulkElem::Bool => 1,
        };
        self.raw(&format!(
            "{}int2dds_cdr_write_prim_array(&w, {}, {}, {});\n",
            indent, data, count, size
        ));
    }

    /// Emit the single call that reads a whole bulk-eligible element run.
    fn emit_bulk_read(&mut self, kind: BulkElem, data: &str, count: &str, indent: &str) {
        let call = match kind {
            BulkElem::Prim(size) => {
                format!("int2dds_cdr_read_prim_array(&r, {}, {}, {})", data, count, size)
            }
            BulkElem::Bool => format!("int2dds_cdr_read_bool_array(&r, {}, {})", data, count),
        };
        self.raw(&format!("{}{};\n", indent, call));
    }

    /// Check if a sequence needs an outer DHEADER in XCDR2.
    /// Enum and bitmask are constructed types, not primitives, so they need a DHEADER
    /// too (DDS-XTypes 7.4.3.5.3/7.4.3.5.4). OMG issue DDSXTY14-56 proposes exempting
    /// them; it is unresolved, so this follows the spec as written.
    fn sequence_element_needs_dheader(element: &ResolvedType) -> bool {
        match element {
            ResolvedType::String { .. }
            | ResolvedType::WString { .. }
            | ResolvedType::Struct(_)
            | ResolvedType::Enum(_)
            | ResolvedType::Bitmask(_)
            | ResolvedType::Sequence { .. }
            | ResolvedType::Array { .. }
            | ResolvedType::Map { .. } => true,
            _ => false,
        }
    }

    /// Whether an array frames itself. A multidimensional IDL array parses to nested
    /// `Array` but XTypes treats it as one array of the base type (7.4.3.4), so look
    /// through the dimensions. Mirrors Rust's `[T; N]::BASE_IS_PRIMITIVE`.
    fn array_needs_dheader(element: &ResolvedType) -> bool {
        match element {
            ResolvedType::Array { element, .. } => Self::array_needs_dheader(element),
            other => Self::sequence_element_needs_dheader(other),
        }
    }

    /// Look up a bitset by name, returning it if found.
    fn find_bitset(&self, name: &str) -> Option<&ResolvedBitset> {
        let simple = name.rsplit("::").next().unwrap_or(name);
        self.model.bitsets.iter().find(|b| b.name == simple)
    }

    /// Look up a bitmask by name, returning it if found.
    fn find_bitmask(&self, name: &str) -> Option<&ResolvedBitmask> {
        let simple = name.rsplit("::").next().unwrap_or(name);
        self.model.bitmasks.iter().find(|b| b.name == simple)
    }

    /// Generate a C struct member declaration for a map key or value field.
    /// Handles string/wstring types specially (like sequence<string>).
    fn map_member_decl(&self, ty: &ResolvedType, field_name: &str, bound: &Option<u32>) -> String {
        // String in FixedArray mode needs 2D array or pointer-to-array
        if let ResolvedType::String { bound: str_bound } = ty {
            if self.opts.string_mode == StringMode::FixedArray {
                let str_size = str_bound.unwrap_or(self.opts.default_string_bound) + 1;
                return if let Some(max) = bound {
                    format!("char {}[{}][{}]", field_name, max, str_size)
                } else {
                    format!("char (*{})[{}]", field_name, str_size)
                };
            }
        }
        // WString needs 2D array or pointer-to-array
        if let ResolvedType::WString { bound: ws_bound } = ty {
            let ws_size = ws_bound.unwrap_or(self.opts.default_string_bound) + 1;
            return if let Some(max) = bound {
                format!("uint16_t {}[{}][{}]", field_name, max, ws_size)
            } else {
                format!("uint16_t (*{})[{}]", field_name, ws_size)
            };
        }
        // Default: use base type
        let base_c = self.type_to_c_base(ty);
        if let Some(max) = bound {
            format!("{} {}[{}]", base_c, field_name, max)
        } else {
            format!("{}* {}", base_c, field_name)
        }
    }

    /// Check if a type has variable-length serialized representation.
    fn type_is_variable_length(&self, ty: &ResolvedType) -> bool {
        match ty {
            ResolvedType::String { .. }
            | ResolvedType::WString { .. }
            | ResolvedType::Sequence { .. }
            | ResolvedType::Map { .. } => true,
            ResolvedType::Array { element, .. } => self.type_is_variable_length(element),
            ResolvedType::Struct(name) => {
                if let Some(s) =
                    self.model.structs.iter().find(|s| s.name == *name || s.qualified_name == *name)
                {
                    s.members.iter().any(|m| self.type_is_variable_length(&m.resolved_type))
                } else {
                    false
                }
            }
            _ => false,
        }
    }

    /// Check if a struct type needs a member-level DHEADER in XCDR2.
    fn struct_needs_member_dheader(&self, type_name: &str) -> bool {
        if let Some(s) =
            self.model.structs.iter().find(|s| s.name == type_name || s.qualified_name == type_name)
        {
            s.extensibility == ExtensibilityKind::Final
                && s.members.iter().any(|m| self.type_is_variable_length(&m.resolved_type))
        } else {
            false
        }
    }

    fn resolved_type_to_field_constant(ty: &ResolvedType) -> Option<&'static str> {
        match ty {
            ResolvedType::Bool => Some("INT2DDS_FIELD_BOOL"),
            ResolvedType::U8 => Some("INT2DDS_FIELD_BYTE"),
            ResolvedType::UInt8 => Some("INT2DDS_FIELD_UINT8"),
            ResolvedType::Char => Some("INT2DDS_FIELD_CHAR8"),
            ResolvedType::WChar => Some("INT2DDS_FIELD_CHAR16"),
            ResolvedType::I8 => Some("INT2DDS_FIELD_INT8"),
            ResolvedType::I16 => Some("INT2DDS_FIELD_INT16"),
            ResolvedType::I32 => Some("INT2DDS_FIELD_INT32"),
            ResolvedType::I64 => Some("INT2DDS_FIELD_INT64"),
            ResolvedType::U16 => Some("INT2DDS_FIELD_UINT16"),
            ResolvedType::U32 => Some("INT2DDS_FIELD_UINT32"),
            ResolvedType::U64 => Some("INT2DDS_FIELD_UINT64"),
            ResolvedType::F32 => Some("INT2DDS_FIELD_FLOAT32"),
            ResolvedType::F64 => Some("INT2DDS_FIELD_FLOAT64"),
            ResolvedType::String { .. } => Some("INT2DDS_FIELD_STRING"),
            ResolvedType::WString { .. } => Some("INT2DDS_FIELD_WSTRING"),
            _ => None,
        }
    }

    fn rust_type_quote_str(ty: &ResolvedType) -> String {
        match ty {
            ResolvedType::Bool => "bool".to_string(),
            ResolvedType::U8 | ResolvedType::UInt8 => "u8".to_string(),
            ResolvedType::I8 => "i8".to_string(),
            ResolvedType::I16 => "i16".to_string(),
            ResolvedType::U16 => "u16".to_string(),
            ResolvedType::I32 => "i32".to_string(),
            ResolvedType::U32 => "u32".to_string(),
            ResolvedType::I64 => "i64".to_string(),
            ResolvedType::U64 => "u64".to_string(),
            ResolvedType::F32 => "f32".to_string(),
            ResolvedType::F64 => "f64".to_string(),
            ResolvedType::Char => "char".to_string(),
            ResolvedType::WChar => "WChar".to_string(),
            ResolvedType::String { .. } => "String".to_string(),
            ResolvedType::WString { .. } => "WString".to_string(),
            ResolvedType::Sequence { element, .. } => {
                format!("Vec < {} >", Self::rust_type_quote_str(element))
            }
            ResolvedType::Array { element, size } => {
                format!("[{} ; {}]", Self::rust_type_quote_str(element), size)
            }
            ResolvedType::Map { key, value, .. } => {
                format!(
                    "HashMap < {} , {} >",
                    Self::rust_type_quote_str(key),
                    Self::rust_type_quote_str(value)
                )
            }
            ResolvedType::Struct(name) | ResolvedType::Enum(name) => {
                let simple = name.rsplit("::").next().unwrap_or(name);
                naming::to_pascal_case(simple)
            }
            ResolvedType::Bitmask(name) => {
                let simple = name.rsplit("::").next().unwrap_or(name);
                format!("{}Value", naming::to_pascal_case(simple))
            }
        }
    }

    fn type_uses_fallback_hash(ty: &ResolvedType) -> bool {
        match ty {
            ResolvedType::Enum(_)
            | ResolvedType::Bitmask(_)
            | ResolvedType::Struct(_)
            | ResolvedType::Map { .. } => true,
            ResolvedType::Sequence { element, .. } => {
                // `add_sequence_field` carries one element kind and one bound, so a
                // collection directly inside a sequence has no spelling there. Without
                // this the member was dropped from the advertised type entirely.
                matches!(
                    element.as_ref(),
                    ResolvedType::Sequence { .. }
                        | ResolvedType::Array { .. }
                        | ResolvedType::Map { .. }
                ) || Self::type_uses_fallback_hash(element)
            }
            ResolvedType::Array { .. } => {
                // Array dims flatten into one plain-array id (`_nd` builders), so only a
                // sequence/map base is left without a spelling. A named base is handled by
                // the nested/named arms before this check runs.
                let (_, base) = flatten_array(ty);
                matches!(base, ResolvedType::Sequence { .. } | ResolvedType::Map { .. })
                    || Self::type_uses_fallback_hash(base)
            }
            _ => false,
        }
    }

    fn member_flags_literal(m: &ResolvedMember) -> String {
        let mut bits: Vec<&str> = Vec::new();
        if m.is_key {
            bits.push("INT2DDS_MEMBER_KEY");
        }
        if m.is_optional {
            bits.push("INT2DDS_MEMBER_OPTIONAL");
        }
        if m.must_understand {
            bits.push("INT2DDS_MEMBER_MUST_UNDERSTAND");
        }
        if m.is_external {
            bits.push("INT2DDS_MEMBER_EXTERNAL");
        }
        if bits.is_empty() {
            "0".to_string()
        } else {
            bits.join(" | ")
        }
    }

    /// Resolve a struct by qualified or leaf name across the local model and imported
    /// (`#include`d) types, mirroring the C#/Python generators' `find_struct`.
    fn find_struct(&self, name: &str) -> Option<&ResolvedStruct> {
        let simple = name.rsplit("::").next().unwrap_or(name);
        self.model
            .structs
            .iter()
            .chain(self.model.imported.structs.iter())
            .find(|s| s.name == simple)
    }

    /// True when `name` resolves to a struct (local or imported), not an enum, bitmask,
    /// bitset, union, or externally-declared type. Only such types have a generated
    /// `{Name}_type_info()` builder to reference by content-hash.
    fn is_model_struct(&self, name: &str) -> bool {
        self.find_struct(name).is_some()
    }

    /// All members including inherited ones (ancestors first), matching the C#/Python
    /// `collect_all_members` so the type_info metadata (and thus KeyHash) covers base
    /// `@key` members.
    fn collect_all_members(&self, s: &ResolvedStruct) -> Vec<ResolvedMember> {
        let mut all = Vec::new();
        if let Some(base_name) = &s.base_type {
            if let Some(base) = self.find_struct(base_name) {
                all.extend(self.collect_all_members(base));
            }
        }
        all.extend(s.members.clone());
        all
    }

    /// The nested in-model struct this member would reference via a content-hash
    /// `{Name}_type_info()` call, if any — the same edges `try_emit_nested_ti` follows.
    fn nested_struct_target(m: &ResolvedMember) -> Option<&str> {
        match &m.resolved_type {
            ResolvedType::Struct(sname) if !m.is_external => Some(sname.as_str()),
            ResolvedType::Sequence { element, .. } | ResolvedType::Array { element, .. } => {
                match element.as_ref() {
                    ResolvedType::Struct(ename) => Some(ename.as_str()),
                    _ => None,
                }
            }
            _ => None,
        }
    }

    /// True when the content-hash nested edges out of `from` can reach `target`
    /// (including `from == target`). Carries its own `visited` set so this walk cannot
    /// itself loop forever on the very cyclic input it guards against.
    fn nested_reaches(
        &self,
        from: &str,
        target: &str,
        visited: &mut std::collections::HashSet<String>,
    ) -> bool {
        let from_simple = from.rsplit("::").next().unwrap_or(from);
        let target_simple = target.rsplit("::").next().unwrap_or(target);
        if from_simple == target_simple {
            return true;
        }
        if !visited.insert(from_simple.to_string()) {
            return false;
        }
        let Some(s) = self.find_struct(from_simple) else {
            return false;
        };
        for m in self.collect_all_members(s) {
            if let Some(next) = Self::nested_struct_target(&m) {
                if self.nested_reaches(next, target_simple, visited) {
                    return true;
                }
            }
        }
        false
    }

    /// If `m` is (or is a sequence/array of) an in-model, non-@external nested struct,
    /// emit its content-hash type_info field — build the nested `{Name}_type_info()`, add
    /// it via the matching `*_nested_field` builder (content-hash CompleteTypeId, so the
    /// runtime resolves the full definition and recurses into @key members, matching derive
    /// and the C#/Python bindings), then destroy it — and return true. Otherwise return
    /// false so the caller falls back to the name-hash / scalar paths.
    fn try_emit_nested_ti(&mut self, m: &ResolvedMember, flags: &str, owner: &str) -> bool {
        let name = &m.name;
        let var = format!("_nti_{}", name);
        let (nested_name, add_stmt) = match &m.resolved_type {
            ResolvedType::Struct(sname) if !m.is_external && self.is_model_struct(sname) => (
                sname,
                format!(
                    "int2dds_type_info_add_nested_field(ti, \"{}\", {}, {});",
                    name, var, flags
                ),
            ),
            ResolvedType::Sequence { element, bound } => match element.as_ref() {
                ResolvedType::Struct(ename) if self.is_model_struct(ename) => (
                    ename,
                    format!(
                        "int2dds_type_info_add_sequence_of_nested_field(ti, \"{}\", {}, {}, {});",
                        name,
                        var,
                        bound.unwrap_or(0),
                        flags
                    ),
                ),
                _ => return false,
            },
            ResolvedType::Array { .. } => {
                let (dims, base) = flatten_array(&m.resolved_type);
                match base {
                    ResolvedType::Struct(ename) if self.is_model_struct(ename) => (
                        ename,
                        if dims.len() > 1 {
                            format!(
                                "const uint32_t _dims_{}[] = {{{}}}; int2dds_type_info_add_array_of_nested_field_nd(ti, \"{}\", {}, _dims_{}, {}, {});",
                                name, dims_literal(&dims), name, var, name, dims.len(), flags
                            )
                        } else {
                            format!(
                                "int2dds_type_info_add_array_of_nested_field(ti, \"{}\", {}, {}, {});",
                                name, var, dims[0], flags
                            )
                        },
                    ),
                    _ => return false,
                }
            }
            _ => return false,
        };
        // Cycle guard: emitting `{nested}_type_info()` inside `{owner}_type_info()` must not
        // close a call-graph cycle (self- or mutual recursion), or the generated C recurses
        // forever. Fall back to the name-hash path for the cyclic edge.
        let mut visited = std::collections::HashSet::new();
        if self.nested_reaches(nested_name, owner, &mut visited) {
            return false;
        }
        let simple = nested_name.rsplit("::").next().unwrap_or(nested_name);
        self.raw("    {\n");
        self.raw(&format!("        Int2DdsTypeInfo *{} = {}_type_info();\n", var, simple));
        self.raw(&format!("        {}\n", add_stmt));
        self.raw(&format!("        int2dds_type_info_destroy({});\n", var));
        self.raw("    }\n");
        true
    }

    fn emit_type_info_field(&mut self, m: &ResolvedMember, owner: &str) {
        let name = &m.name;
        let ty = &m.resolved_type;
        let flags = Self::member_flags_literal(m);

        if self.try_emit_nested_ti(m, &flags, owner) {
            return;
        }

        match ty {
            ResolvedType::Sequence { element, bound }
                if matches!(
                    element.as_ref(),
                    ResolvedType::Struct(_) | ResolvedType::Enum(_) | ResolvedType::Bitmask(_)
                ) =>
            {
                let elem_name = Self::rust_type_quote_str(element);
                self.raw(&format!(
                    "    int2dds_type_info_add_sequence_of_named_field(ti, \"{}\", \"{}\", {}, {});\n",
                    name, elem_name, bound.unwrap_or(0), flags
                ));
                return;
            }
            ResolvedType::Array { .. } => {
                let (dims, base) = flatten_array(ty);
                if matches!(
                    base,
                    ResolvedType::Struct(_) | ResolvedType::Enum(_) | ResolvedType::Bitmask(_)
                ) {
                    let elem_name = Self::rust_type_quote_str(base);
                    if dims.len() > 1 {
                        self.raw(&format!(
                            "    {{ const uint32_t _dims_{}[] = {{{}}}; int2dds_type_info_add_array_of_named_field_nd(ti, \"{}\", \"{}\", _dims_{}, {}, {}); }}\n",
                            name, dims_literal(&dims), name, elem_name, name, dims.len(), flags
                        ));
                    } else {
                        self.raw(&format!(
                            "    int2dds_type_info_add_array_of_named_field(ti, \"{}\", \"{}\", {}, {});\n",
                            name, elem_name, dims[0], flags
                        ));
                    }
                    return;
                }
            }
            _ => {}
        }

        if Self::type_uses_fallback_hash(ty) {
            let hash_name = Self::rust_type_quote_str(ty);
            self.raw(&format!(
                "    int2dds_type_info_add_named_type_field(ti, \"{}\", \"{}\", {});\n",
                name, hash_name, flags
            ));
            return;
        }

        match ty {
            ResolvedType::Sequence { element, bound } => {
                if let Some(elem_const) = Self::resolved_type_to_field_constant(element) {
                    self.raw(&format!(
                        "    int2dds_type_info_add_sequence_field(ti, \"{}\", {}, {}, {});\n",
                        name,
                        elem_const,
                        bound.unwrap_or(0),
                        flags
                    ));
                }
            }
            ResolvedType::Array { .. } => {
                let (dims, base) = flatten_array(ty);
                if let Some(elem_const) = Self::resolved_type_to_field_constant(base) {
                    if dims.len() > 1 {
                        self.raw(&format!(
                            "    {{ const uint32_t _dims_{}[] = {{{}}}; int2dds_type_info_add_array_field_nd(ti, \"{}\", {}, _dims_{}, {}, {}); }}\n",
                            name, dims_literal(&dims), name, elem_const, name, dims.len(), flags
                        ));
                    } else {
                        self.raw(&format!(
                            "    int2dds_type_info_add_array_field(ti, \"{}\", {}, {}, {});\n",
                            name, elem_const, dims[0], flags
                        ));
                    }
                }
            }
            ResolvedType::String { bound } => {
                self.raw(&format!(
                    "    int2dds_type_info_add_string_field(ti, \"{}\", {}, {});\n",
                    name,
                    bound.unwrap_or(0),
                    flags
                ));
            }
            ResolvedType::WString { bound } => {
                self.raw(&format!(
                    "    int2dds_type_info_add_wstring_field(ti, \"{}\", {}, {});\n",
                    name,
                    bound.unwrap_or(0),
                    flags
                ));
            }
            _ => {
                if let Some(field_const) = Self::resolved_type_to_field_constant(ty) {
                    self.raw(&format!(
                        "    int2dds_type_info_add_field(ti, \"{}\", {}, {});\n",
                        name, field_const, flags
                    ));
                }
            }
        }
    }

    fn emit_type_info_fn(&mut self, s: &ResolvedStruct) {
        let ext_int = match s.extensibility {
            ExtensibilityKind::Final => 0,
            ExtensibilityKind::Appendable => 1,
            ExtensibilityKind::Mutable => 2,
        };

        self.raw(&format!("static inline Int2DdsTypeInfo* {}_type_info(void) {{\n", s.name));
        self.raw("    Int2DdsTypeInfo *ti;\n");
        self.raw(&format!(
            "    int2dds_type_info_create(\"{}\", {}, &ti);\n",
            s.qualified_name, ext_int
        ));

        let members = self.collect_all_members(s);
        for m in &members {
            self.emit_type_info_field(m, &s.name);
        }

        self.raw("    return ti;\n}\n");
    }

    /// Emit a `{Name}_create_topic` convenience wrapper. Extensibility is carried by the
    /// type through `{Name}_type_info()`, so C callers create a topic without passing an
    /// extensibility argument — parity with the Python/C# bindings, where extensibility is
    /// a property of the type rather than a `create_topic` parameter. Works for keyed types
    /// too, since the type-info path derives the key from the TypeObject. Requires
    /// `int2dds-ffi.h` (same prerequisite as `{Name}_type_info`).
    fn emit_create_topic_fn(&mut self, s: &ResolvedStruct) {
        self.raw(&format!(
            "static inline Int2DdsRet {}_create_topic(const Int2DdsParticipant *participant, const char *topic_name, const Int2DdsTopicQos *qos, Int2DdsTopic **topic_out) {{\n",
            s.name
        ));
        self.raw(&format!("    Int2DdsTypeInfo *ti = {}_type_info();\n", s.name));
        self.raw(
            "    Int2DdsRet ret = int2dds_create_topic_with_type_info(participant, topic_name, ti, qos, topic_out);\n",
        );
        self.raw("    int2dds_type_info_destroy(ti);\n");
        self.raw("    return ret;\n}\n");
    }

    // ---- Memory Management (Pointer mode) ----

    fn type_needs_cleanup(&self, ty: &ResolvedType) -> bool {
        match ty {
            ResolvedType::String { .. } => true,
            ResolvedType::Sequence { element, bound } => {
                bound.is_none() || self.type_needs_cleanup(element)
            }
            ResolvedType::Map { key, value, bound } => {
                bound.is_none() || self.type_needs_cleanup(key) || self.type_needs_cleanup(value)
            }
            ResolvedType::Array { element, .. } => self.type_needs_cleanup(element),
            ResolvedType::Struct(name) => {
                if let Some(nested) =
                    self.model.structs.iter().find(|s| s.name == *name || s.qualified_name == *name)
                {
                    self.struct_needs_cleanup(nested)
                } else if let Some(nested) =
                    self.model.unions.iter().find(|u| u.name == *name || u.qualified_name == *name)
                {
                    self.union_needs_cleanup(nested)
                } else {
                    false
                }
            }
            _ => false,
        }
    }

    fn struct_needs_cleanup(&self, s: &ResolvedStruct) -> bool {
        s.members.iter().any(|m| self.type_needs_cleanup(&m.resolved_type))
    }

    fn union_needs_cleanup(&self, u: &ResolvedUnion) -> bool {
        u.cases.iter().any(|c| self.type_needs_cleanup(&c.member.resolved_type))
            || u.default_case.as_ref().is_some_and(|dc| self.type_needs_cleanup(&dc.resolved_type))
    }

    fn emit_struct_init(&mut self, s: &ResolvedStruct) {
        self.raw(&format!("static inline void {}_init({} *val) {{\n", s.name, s.name));
        self.raw("    memset(val, 0, sizeof(*val));\n");
        self.raw("}\n");
    }

    fn emit_struct_cleanup(&mut self, s: &ResolvedStruct) {
        self.raw(&format!("static inline void {}_cleanup({} *val) {{\n", s.name, s.name));

        for m in &s.members {
            let field_name = naming::escape_keyword(&m.name, naming::TargetLang::C);
            let accessor = format!("val->{}", field_name);
            self.emit_cleanup_field(&m.resolved_type, &accessor, "    ");
        }

        self.raw("}\n");
    }

    fn emit_union_cleanup(&mut self, u: &ResolvedUnion) {
        self.raw(&format!("static inline void {}_cleanup({} *val) {{\n", u.name, u.name));
        self.raw("    switch (val->_d) {\n");
        for case in &u.cases {
            if !self.type_needs_cleanup(&case.member.resolved_type) {
                continue;
            }
            for label in &case.labels {
                self.raw(&format!("    case {}:\n", self.union_label_c(label)));
            }
            let case_name = naming::escape_keyword(&case.member.name, naming::TargetLang::C);
            let accessor = format!("val->_u.{}", case_name);
            self.emit_cleanup_field(&case.member.resolved_type, &accessor, "        ");
            self.raw("        break;\n");
        }
        if let Some(dc) = &u.default_case {
            if self.type_needs_cleanup(&dc.resolved_type) {
                self.raw("    default:\n");
                let dc_name = naming::escape_keyword(&dc.name, naming::TargetLang::C);
                let accessor = format!("val->_u.{}", dc_name);
                self.emit_cleanup_field(&dc.resolved_type, &accessor, "        ");
                self.raw("        break;\n");
            }
        }
        self.raw("    }\n}\n");
    }

    fn emit_cleanup_field(&mut self, ty: &ResolvedType, accessor: &str, indent: &str) {
        match ty {
            ResolvedType::String { .. } => {
                self.raw(&format!(
                    "{}if ({}) {{ free({}); {} = NULL; }}\n",
                    indent, accessor, accessor, accessor
                ));
            }
            ResolvedType::Sequence { element, bound } => {
                if self.type_needs_cleanup(element) {
                    self.raw(&format!(
                        "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                        indent, accessor
                    ));
                    let elem_accessor = format!("{}.data[_i]", accessor);
                    self.emit_cleanup_field(element, &elem_accessor, &format!("{}    ", indent));
                    self.raw(&format!("{}}}\n", indent));
                }
                if bound.is_none() {
                    self.raw(&format!(
                        "{}if ({}.data) {{ free({}.data); {}.data = NULL; }}\n",
                        indent, accessor, accessor, accessor
                    ));
                }
            }
            ResolvedType::Map { key, value, bound } => {
                if self.type_needs_cleanup(key) {
                    self.raw(&format!(
                        "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                        indent, accessor
                    ));
                    let key_accessor = format!("{}.keys[_i]", accessor);
                    self.emit_cleanup_field(key, &key_accessor, &format!("{}    ", indent));
                    self.raw(&format!("{}}}\n", indent));
                }
                if self.type_needs_cleanup(value) {
                    self.raw(&format!(
                        "{}for (uint32_t _i = 0; _i < {}.length; _i++) {{\n",
                        indent, accessor
                    ));
                    let val_accessor = format!("{}.values[_i]", accessor);
                    self.emit_cleanup_field(value, &val_accessor, &format!("{}    ", indent));
                    self.raw(&format!("{}}}\n", indent));
                }
                if bound.is_none() {
                    self.raw(&format!(
                        "{}if ({}.keys) {{ free({}.keys); {}.keys = NULL; }}\n",
                        indent, accessor, accessor, accessor
                    ));
                    self.raw(&format!(
                        "{}if ({}.values) {{ free({}.values); {}.values = NULL; }}\n",
                        indent, accessor, accessor, accessor
                    ));
                }
            }
            ResolvedType::Array { element, size } => {
                if self.type_needs_cleanup(element) {
                    self.raw(&format!("{}for (uint32_t _i = 0; _i < {}; _i++) {{\n", indent, size));
                    let elem_accessor = format!("{}[_i]", accessor);
                    self.emit_cleanup_field(element, &elem_accessor, &format!("{}    ", indent));
                    self.raw(&format!("{}}}\n", indent));
                }
            }
            // A `_cleanup` definition only exists when the struct or union needs one
            // (never for bitsets, which also resolve as `Struct`).
            ResolvedType::Struct(type_name) if self.type_needs_cleanup(ty) => {
                let simple = type_name.rsplit("::").next().unwrap_or(type_name);
                self.raw(&format!("{}{}_cleanup(&{});\n", indent, simple, accessor));
            }
            _ => {} // Primitives don't need cleanup
        }
    }

    // ---- Helpers ----

    fn raw(&mut self, text: &str) {
        self.out.push_str(text);
    }
}

