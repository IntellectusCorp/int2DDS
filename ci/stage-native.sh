#!/usr/bin/env bash
# Stage the built native artifacts into a release archive (Linux / macOS).
#
# Usage: ci/stage-native.sh <triple> <dist_name> <version> [<libc>]
#   e.g. ci/stage-native.sh x86_64-unknown-linux-gnu linux-x86_64 0.1.1 gnu
#        ci/stage-native.sh aarch64-apple-darwin macos-arm64 0.1.1
set -euo pipefail

triple="${1:?usage: stage-native.sh <triple> <dist_name> <version> [libc]}"
dist_name="${2:?}"
version="${3:?}"
libc="${4:-}"

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
build_dir="$repo_root/target/$triple/release"
stage="$repo_root/dist/stage/int2dds-$version-$dist_name"
out_dir="$repo_root/dist"

rm -rf "$stage"
mkdir -p "$stage"/{lib,include,src,bin} "$out_dir"

case "$(uname -s)" in
  Darwin) lib_file="libint2dds_ffi.dylib" ;;
  *)      lib_file="libint2dds_ffi.so" ;;
esac

if [[ ! -f "$build_dir/$lib_file" ]]; then
  echo "ERROR: $build_dir/$lib_file not found — did the cargo build run?" >&2
  exit 1
fi

if [[ "$lib_file" == "libint2dds_ffi.so" ]]; then
  # Build the three-level SONAME chain: .so -> .so.<major> -> .so.<version>
  major="${version%%.*}"
  cp "$build_dir/$lib_file" "$stage/lib/libint2dds_ffi.so.$version"
  ln -sfn "libint2dds_ffi.so.$version" "$stage/lib/libint2dds_ffi.so.$major"
  ln -sfn "libint2dds_ffi.so.$major"   "$stage/lib/libint2dds_ffi.so"
  real_lib="$stage/lib/libint2dds_ffi.so.$version"
else
  cp "$build_dir/$lib_file" "$stage/lib/$lib_file"
  real_lib="$stage/lib/$lib_file"
fi

# IDL compiler CLI.
if [[ ! -f "$build_dir/int2dds-idl" ]]; then
  echo "ERROR: $build_dir/int2dds-idl not found" >&2
  exit 1
fi
cp "$build_dir/int2dds-idl" "$stage/bin/int2dds-idl"

# The two headers and the CDR implementation.
# int2dds_cdr.h / cdr_utils.c must ship along, because the C code generated by
# idl/src/codegen/c.rs includes them.
cp "$repo_root/ffi/include/int2dds-ffi.h" "$stage/include/"
cp "$repo_root/ffi/include/int2dds_cdr.h" "$stage/include/"
cp "$repo_root/ffi/src/cdr_utils.c"       "$stage/src/"

cp "$repo_root/LICENSE" "$repo_root/NOTICE" "$repo_root/Third_Party_Licenses.md" "$stage/"

# Generate the manifest.
manifest="$stage/manifest.txt"
sha="$(sha256sum "$real_lib" 2>/dev/null | cut -d' ' -f1 || shasum -a 256 "$real_lib" | cut -d' ' -f1)"
{
  echo "name: int2dds"
  echo "version: \"$version\""
  echo "api_header: int2dds-ffi.h"
  echo "license: Apache-2.0"
  echo "triple: $triple"
  echo "dist: $dist_name"
  echo "sha256: $sha"
} > "$manifest"

if [[ "$lib_file" == "libint2dds_ffi.so" ]]; then
  soname="$(readelf -d "$real_lib" | sed -n 's/.*SONAME.*\[\(.*\)\].*/\1/p')"
  [[ -n "$soname" ]] || soname="libint2dds_ffi.so.${version%%.*}"
  echo "soname: $soname" >> "$manifest"

  if [[ "$libc" == "musl" ]]; then
    echo "libc: musl" >> "$manifest"
  else
    glibc="$(readelf -V "$real_lib" | grep -oE 'GLIBC_[0-9.]+' | sed 's/GLIBC_//' | sort -V | tail -1 || true)"
    [[ -n "$glibc" ]] || glibc="unknown"
    echo "min_glibc: \"$glibc\"" >> "$manifest"

    # glibc baseline regression guard: fail if it exceeds 2.35 (ubuntu 22.04).
    if [[ "$glibc" != "unknown" ]] && \
       [[ "$(printf '%s\n2.35\n' "$glibc" | sort -V | tail -1)" != "2.35" ]]; then
      echo "ERROR: min_glibc $glibc exceeds the 2.35 baseline" >&2
      exit 1
    fi
  fi
else
  echo "install_name: $(otool -D "$real_lib" | tail -1)" >> "$manifest"
  echo "deployment_target: \"${MACOSX_DEPLOYMENT_TARGET:-unset}\"" >> "$manifest"
fi

# Create the archive. --dereference would flatten the symlinks into real files
# and break the SONAME chain.
archive="$out_dir/int2dds-$version-$dist_name.tar.gz"
tar -czf "$archive" -C "$repo_root/dist/stage" "int2dds-$version-$dist_name"

echo "== manifest =="; cat "$manifest"
echo "== archive =="; tar -tzf "$archive"
echo "$archive"
