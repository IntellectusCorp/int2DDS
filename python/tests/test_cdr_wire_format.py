WSTRING_VALUE = "w☃한"


def _writer(fmt: str) -> CdrWriter:
    if fmt == "xcdr1_le":
        return CdrWriter(Extensibility.FINAL, little_endian=True, xcdr2=False)
    if fmt == "xcdr1_be":
        return CdrWriter(Extensibility.FINAL, little_endian=False, xcdr2=False)
    if fmt == "xcdr2_le":
        return CdrWriter(Extensibility.FINAL, little_endian=True, xcdr2=True)
    raise ValueError(fmt)


def _write_shape(w: CdrWriter, shape: str) -> None:
    if shape == "bool_true":
        w.write_bool(True)
    elif shape == "u8":
        w.write_u8(0xAB)
    elif shape == "i8":
        w.write_i8(-5)
    elif shape == "u16":
        w.write_u16(0xBEEF)
    elif shape == "i16":
        w.write_i16(-12345)
    elif shape == "u32":
        w.write_u32(0xDEADBEEF)
    elif shape == "i32":
        w.write_i32(-123456789)
    elif shape == "u64":
        w.write_u64(0x1122334455667788)
    elif shape == "i64":
        w.write_i64(-1234567890123456789)
    elif shape == "f32":
        w.write_f32(1.5)
    elif shape == "f64":
        w.write_f64(-2.75)
    elif shape == "string":
        w.write_string("hello")
    elif shape == "string_empty":
        w.write_string("")
    elif shape == "wstring":
        w.write_wstring(WSTRING_VALUE)
    elif shape == "wstring_empty":
        w.write_wstring("")
    elif shape == "bytes":
        w.write_seq_header(5)
        w.write_bytes(bytes([1, 2, 3, 4, 5]))
    elif shape == "seq_u32":
        w.write_seq_header(3)
        w.write_u32(1)
        w.write_u32(0x7FFFFFFF)
        w.write_u32(0xFFFFFFFF)
    elif shape == "mixed":
        w.write_u8(0x42)
        w.write_u64(0x0102030405060708)
        w.write_i16(-2)
        w.write_u32(0x0A0B0C0D)
        w.write_string("ok")
        w.write_f64(1.0)
    else:
        raise ValueError(shape)


def _read_shape(r: CdrReader, shape: str) -> None:
    if shape == "bool_true":
        assert r.read_bool() is True
    elif shape == "u8":
        assert r.read_u8() == 0xAB
    elif shape == "i8":
        assert r.read_i8() == -5
    elif shape == "u16":
        assert r.read_u16() == 0xBEEF
    elif shape == "i16":
        assert r.read_i16() == -12345
    elif shape == "u32":
        assert r.read_u32() == 0xDEADBEEF
    elif shape == "i32":
        assert r.read_i32() == -123456789
    elif shape == "u64":
        assert r.read_u64() == 0x1122334455667788
    elif shape == "i64":
        assert r.read_i64() == -1234567890123456789
    elif shape == "f32":
        assert r.read_f32() == 1.5
    elif shape == "f64":
        assert r.read_f64() == -2.75
    elif shape == "string":
        assert r.read_string() == "hello"
    elif shape == "string_empty":
        assert r.read_string() == ""
    elif shape == "wstring":
        assert r.read_wstring() == WSTRING_VALUE
    elif shape == "wstring_empty":
        assert r.read_wstring() == ""
    elif shape == "bytes":
        assert r.read_seq_header() == 5
        assert r.read_bytes(5) == bytes([1, 2, 3, 4, 5])
    elif shape == "seq_u32":
        assert r.read_seq_header() == 3
        assert r.read_u32() == 1
        assert r.read_u32() == 0x7FFFFFFF
        assert r.read_u32() == 0xFFFFFFFF
    elif shape == "mixed":
        assert r.read_u8() == 0x42
        assert r.read_u64() == 0x0102030405060708
        assert r.read_i16() == -2
        assert r.read_u32() == 0x0A0B0C0D
        assert r.read_string() == "ok"
        assert r.read_f64() == 1.0
    else:
        raise ValueError(shape)


@pytest.mark.parametrize("shape,fmt,expected", VECTORS)
def test_writer_produces_reference_bytes(shape, fmt, expected):
    w = _writer(fmt)
    _write_shape(w, shape)
    assert w.to_bytes().hex() == expected


@pytest.mark.parametrize("shape,fmt,expected", VECTORS)
def test_reader_consumes_reference_bytes(shape, fmt, expected):
    r = CdrReader(bytes.fromhex(expected))
    _read_shape(r, shape)
    assert r.remaining == 0
